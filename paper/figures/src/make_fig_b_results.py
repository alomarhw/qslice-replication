"""The RQ2 and RQ4 figures, in the style of the scale figure (make_fig_scale.py).

fig_b_coverage: (a) why the programs of LintQ's corpus that yield no circuit yield none, by the rule of
results/icpc/scale__rerun-20261101/coverage_reasons.json; (b) the methods whose effect a trace most often misses or blurs there, from
results/icpc/unmodelled__rerun-20261101/summary.json, split into methods not modelled and methods whose result is unknown.
fig_b_share: the share of a program's code lines that a qubit's slice holds, over every sliced qubit of LintQ's corpus,
from results/icpc/scale__rerun-20261101/s1_lintq.csv, with the median that make_numbers.py reports as ScaleReadMedianPct.
Usage (from the workspace root): python paper/figures/src/make_fig_b_results.py -> paper/figures/src/fig_b_{coverage,share}.tex
"""
import csv
import json
import statistics as st
from pathlib import Path

SRC = Path(__file__).resolve().parent
ROOT = SRC.parents[2]
RES = ROOT / "experiments" / "results" / "icpc"

HEAD = r"""% Generated by make_fig_b_results.py from committed results. Do not edit by hand.
\documentclass[border=2pt]{standalone}
\usepackage[T1]{fontenc}\usepackage{newtxtext,newtxmath}\usepackage[varqu,scaled=0.95]{zi4}
\usepackage{pgfplots}\pgfplotsset{compat=1.18}\usepgfplotslibrary{groupplots}
\definecolor{cblue}{HTML}{0072B2}\definecolor{cver}{HTML}{D55E00}\definecolor{cora}{HTML}{E69F00}
\definecolor{cgreen}{HTML}{009E73}\definecolor{cgrey}{HTML}{999999}
\pgfplotsset{every axis/.append style={font=\footnotesize, tick label style={font=\scriptsize},
  label style={font=\footnotesize}, legend style={font=\scriptsize, draw=none, fill=none},
  axis lines*=left, grid style={black!8}}}
\begin{document}
"""


def coverage():
    reasons = json.load(open(RES / "scale__rerun-20261101" / "coverage_reasons.json"))
    um = json.load(open(RES / "unmodelled__rerun-20261101" / "summary.json"))["lintq"]
    a = [("never builds a circuit", reasons["no-construction"]),
         ("builds it in code not followed", reasons["other"]),
         ("loads it from a file or library", reasons["from-file-or-lib"])]
    assert sum(v for _, v in a) == reasons["no_circuit_files"]
    meth = [(m, n, "not modelled") for m, n in um["method_not_modelled"]["top"]] + \
           [(m, n, "result unknown") for m, n in um["result_unknown"]["top"]]
    meth = sorted(meth, key=lambda t: -t[1])[:8]
    o = [HEAD, r"\begin{tikzpicture}"]
    # (a) reasons, horizontal bars
    ya = ",".join("{%s}" % lab for lab, _ in reversed(a))
    o.append(r"\begin{axis}[name=a, xbar, width=4.3cm, height=2.6cm, bar width=7pt, xmin=0, xmax=%d, "
             r"symbolic y coords={%s}, ytick=data, xmajorgrids, xlabel={programs}, "
             r"nodes near coords, nodes near coords style={font=\scriptsize, anchor=west}, enlarge y limits=0.3, "
             r"title={\footnotesize (a) no circuit, %s programs}, title style={at={(0,1)}, anchor=south west, xshift=-3.6cm}]"
             % (int(a[0][1] * 1.35), ya, f"{reasons['no_circuit_files']:,}".replace(",", "{,}")))
    o.append(r"\addplot[fill=cgrey!60, draw=none] coordinates {%s};" % " ".join(f"({v},{{{lab}}})" for lab, v in a))
    o.append(r"\end{axis}")
    # (b) methods, coloured by kind
    yb = ",".join(r"{\texttt{%s}}" % m.replace("_", r"\_") for m, _, _ in reversed(meth))
    o.append(r"\begin{axis}[at={(a.south west)}, anchor=north west, yshift=-1.75cm, xbar stacked, width=4.3cm, height=4.3cm, "
             r"bar width=6pt, xmin=0, xmax=%d, symbolic y coords={%s}, ytick=data, xmajorgrids, xlabel={programs}, "
             r"enlarge y limits=0.08, legend style={at={(1,0.02)}, anchor=south east, legend columns=1}, legend cell align=left, "
             r"title={\footnotesize (b) methods whose effect a trace misses or blurs}, title style={at={(0,1)}, anchor=south west, xshift=-3.6cm}]"
             % (int(meth[0][1] * 1.2), yb))
    for kind, col in (("not modelled", "cver"), ("result unknown", "cora")):
        pts = " ".join(r"(%d,{\texttt{%s}})" % (n if k == kind else 0, m.replace("_", r"\_")) for m, n, k in meth)
        o.append(r"\addplot[fill=%s, draw=none] coordinates {%s};" % (col, pts))
        o.append(r"\addlegendentry{%s}" % kind)
    o.append(r"\end{axis}")
    o.append(r"\end{tikzpicture}")
    o.append(r"\end{document}")
    (SRC / "fig_b_coverage.tex").write_text("\n".join(o) + "\n")


def share():
    rows = [r for r in csv.DictReader(open(RES / "scale__rerun-20261101" / "s1_lintq.csv")) if not r["error"]]
    sh = [int(x) / int(r["code_lines"]) for r in rows if int(r["code_lines"]) for x in r["slice_lines"].split(";") if x]
    med = st.median(sh)
    bins = [0] * 20
    for v in sh:
        bins[min(int(v * 20), 19)] += 1
    o = [HEAD, r"\begin{tikzpicture}"]
    o.append(r"\begin{axis}[width=8.6cm, height=3.9cm, ybar, bar width=4.4, xmin=0, xmax=100, ymin=0, enlarge x limits=false, "
             r"xtick={0,25,50,75,100}, xticklabel={\pgfmathprintnumber{\tick}\%}, ymajorgrids, "
             r"xlabel={share of the program's code lines in a qubit's slice}, ylabel={qubits}, "
             r"scaled y ticks=false, yticklabel style={/pgf/number format/1000 sep={}}]")
    o.append(r"\addplot[fill=cblue!70, draw=none] coordinates {%s};"
             % " ".join(f"({5 * i + 2.5},{n})" for i, n in enumerate(bins)))
    o.append(r"\draw[cver, line width=0.9pt, dashed] ({axis cs:%.2f,0}|-{rel axis cs:0,0}) -- ({axis cs:%.2f,0}|-{rel axis cs:0,1}) "
             r"node[anchor=north west, font=\scriptsize, text=cver] {median %.0f\%%};" % (100 * med, 100 * med, 100 * med))
    o.append(r"\end{axis}")
    o.append(r"\end{tikzpicture}")
    o.append(r"\end{document}")
    (SRC / "fig_b_share.tex").write_text("\n".join(o) + "\n")
    print(f"share: {len(sh)} qubits, median {med:.3f}")


if __name__ == "__main__":
    coverage()
    share()
