"""Generate the motivating figure from a real Bugs4Q bug (stackoverflow-6-10/bug_2) and the study's code.

The developer meant to prepare (|01> + |10>)/sqrt(2) and wrote circuit.h(1) where circuit.x(1) was needed.
The original buggy and fixed files of Bugs4Q (commit 7a71983, Apache-2.0) are READ, never executed: the
three gate lines are checked against the text this script rebuilds the circuit from. Outcome
probabilities come from an exact statevector; slices from experiments/slicers/registry.py; dependences
from experiments/icpc/influence.py; fidelities from experiments/icpc/oracle_icpc.py.
Writes fig_motivating.tex and fig_motivating_facts.json next to this file.
Usage (from experiments/): python ../paper/figures/src/make_fig_motivating.py BUGS4Q_ROOT
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent
EXP = SRC.parents[2] / "experiments"
sys.path.insert(0, str(EXP))
BUG = "stackoverflow-6-10/bug_2"
GATE_LINES = {5: "circuit.h(0)", 6: "circuit.h(1)", 7: "circuit.cx(0,1)"}   # buggy.py
FIX_LINE = (6, "circuit.x(1)")                                               # fixed.py


def circuits():
    from qiskit import QuantumCircuit
    def mk(fixed):
        qc = QuantumCircuit(2)
        qc.h(0)
        qc.x(1) if fixed else qc.h(1)
        qc.cx(0, 1)
        return qc
    return mk(False), mk(True), [5, 6, 7]


def main():
    root = Path(sys.argv[1]) / BUG
    buggy = (root / "buggy.py").read_text().splitlines()
    fixed = (root / "fixed.py").read_text().splitlines()
    for ln, text in GATE_LINES.items():
        assert buggy[ln - 1].strip() == text, (ln, buggy[ln - 1])
    assert fixed[FIX_LINE[0] - 1].strip() == FIX_LINE[1]
    from qiskit.quantum_info import Statevector
    from common.evaluate import materialise
    from icpc import oracle_icpc as oi
    from icpc.influence import influence, influence_sets
    from icpc.cpdg import cpdg_slice
    from slicers.registry import Slicers
    B, Fx, lines = circuits()
    pb, pf = Statevector(B).probabilities_dict(), Statevector(Fx).probabilities_dict()
    rb, rf = oi.reduced_states(B, [0, 1]), oi.reduced_states(Fx, [0, 1])
    s = Slicers(B, "motivating")
    dep = influence_sets(influence(B), 2)
    du0, lc0 = sorted(cpdg_slice(B, 0)), sorted(s.lc(0))
    assert du0 == sorted(s.du(0))  # no classical bits here, so the classical PDG equals def-use
    f_du = oi.uhlmann_fidelity(rb[0], oi.reduced_states(materialise(B, set(du0)), [0])[0])
    facts = {"P_buggy": pb, "P_fixed": pf,
             "P1_buggy": [float(rb[q][1, 1].real) for q in (0, 1)], "P1_fixed": [float(rf[q][1, 1].real) for q in (0, 1)],
             "F_q0_buggy_vs_fixed": float(oi.uhlmann_fidelity(rb[0], rf[0])),
             "dep_q0": sorted(dep[0]), "du_q0": du0, "lc_q0": lc0, "F_du_q0_at_00": float(f_du), "lines": lines}
    (SRC / "fig_motivating_facts.json").write_text(json.dumps(facts, indent=1))
    keys = ["00", "01", "10", "11"]
    lab = lambda sl: ", ".join(str(lines[k]) for k in sl)  # noqa: E731

    code_rows = []
    for ln in range(4, 9):
        text = buggy[ln - 1].replace("_", "\\char`\\_").replace("{", "\\{").replace("}", "\\}")
        mark = "\\fcolorbox{cver}{cver!10}" if ln == FIX_LINE[0] else "\\fcolorbox{white}{white}"
        note = (f"\\ \\textcolor{{cver}}{{\\scriptsize$\\leftarrow$ fix: \\texttt{{{FIX_LINE[1].replace('_', chr(92) + '_')}}}}}"
                if ln == FIX_LINE[0] else "")
        code_rows.append(f"{{\\tiny\\color{{black!50}}{ln}}} & {mark}{{\\ttfamily\\scriptsize {text}}}{note} \\\\")

    def qcirc(slice_, miss):
        def cell(k, body):
            sty = ("fill=cblue!28,draw=none" if k in slice_ else
                   "draw=cver,line width=0.8pt,dash pattern=on 2pt off 1.2pt,fill=none" if k in miss else None)
            return body + (f"\\gategroup[wires={2 if k == 2 else 1},steps=1,style={{{sty},rounded corners=2pt,inner sep=0.4pt}},background]{{}}"
                           if sty else "")
        r0 = ["\\lstick{$q_0$}", cell(0, "\\gate{H}"), "", cell(2, "\\ctrl{1}"), "\\rstick{\\scriptsize criterion}"]
        r1 = ["\\lstick{$q_1$}", "", cell(1, "\\gate{H}"), "\\targ{}", ""]
        return ("\\begin{quantikz}[row sep={0.6cm,between origins}, column sep=0.22cm]\n"
                + " & ".join(r0) + " \\\\\n" + " & ".join(r1) + "\n\\end{quantikz}")

    miss_du = set(dep[0]) - set(du0)
    tex = [
        "% Generated by make_fig_motivating.py from Bugs4Q stackoverflow-6-10/bug_2 and the study's code. Do not edit by hand.",
        "\\documentclass[border=3pt,varwidth=8.7cm]{standalone}",
        "\\usepackage[T1]{fontenc}\\usepackage{newtxtext,newtxmath}\\usepackage[varqu,scaled=0.95]{zi4}",
        "\\usepackage{amsmath,xcolor,pgfplots}\\pgfplotsset{compat=1.18}",
        "\\usepackage{tikz}\\usetikzlibrary{quantikz2}",
        "\\providecommand{\\ket}[1]{\\lvert #1\\rangle}",
        "\\definecolor{cblue}{HTML}{0072B2}\\definecolor{cver}{HTML}{D55E00}\\definecolor{cgrey}{HTML}{999999}",
        "\\setlength{\\fboxsep}{1pt}",
        "\\begin{document}\\begin{varwidth}{8.7cm}\\centering",
        "{\\footnotesize\\textbf{(a) Buggy program} (Bugs4Q, Stack Overflow)}\\\\[2pt]",
        "\\begin{tabular}{@{}r@{\\hspace{4pt}}l@{}}", *code_rows, "\\end{tabular}\\\\[5pt]",
        "{\\footnotesize\\textbf{(b) Measured outcomes} ($q_1q_0$, exact probabilities)}\\\\[1pt]",
        "\\begin{tikzpicture}\\begin{axis}[ybar, bar width=7pt, width=7.6cm, height=3.0cm, ymin=0, ymax=0.62,"
        " symbolic x coords={" + ",".join(keys) + "}, xtick=data, tick label style={font=\\scriptsize},"
        " ylabel={\\scriptsize probability}, ytick={0,0.25,0.5}, area legend, legend style={font=\\scriptsize, draw=none, fill=none, at={(0.5,1.03)}, anchor=south, legend columns=2, /tikz/every even column/.append style={column sep=8pt}},"
        " axis lines*=left, enlarge x limits=0.18, ymajorgrids, grid style={black!8}]",
        "\\addplot[fill=cver!70, draw=none] coordinates {" + " ".join(f"({k},{pb.get(k, 0):.3f})" for k in keys) + "};",
        "\\addplot[fill=cgrey!60, draw=none] coordinates {" + " ".join(f"({k},{pf.get(k, 0):.3f})" for k in keys) + "};",
        "\\legend{buggy, intended}",
        "\\end{axis}\\end{tikzpicture}\\\\[-2pt]",
        f"{{\\scriptsize each qubit alone reads 1 with probability {facts['P1_buggy'][0]:.1f} in both versions}}\\\\[5pt]",
        "{\\footnotesize\\textbf{(c) Slices of $q_0$ in the buggy program}}\\\\[2pt]",
        "\\begin{minipage}[t]{0.49\\linewidth}\\centering{\\scriptsize Classical PDG: line " + lab(du0) + "}\\\\" + qcirc(set(du0), miss_du) + "\\end{minipage}\\hfill",
        "\\begin{minipage}[t]{0.49\\linewidth}\\centering{\\scriptsize Wire rule: lines " + lab(lc0) + "}\\\\" + qcirc(set(lc0), set()) + "\\end{minipage}",
        "\\end{varwidth}\\end{document}",
    ]
    (SRC / "fig_motivating.tex").write_text("\n".join(tex) + "\n")
    print(json.dumps({k: v for k, v in facts.items() if not k.startswith("P_")}))


if __name__ == "__main__":
    main()
