"""Fig. 2: the architecture of the approach, with what each part produces on the program of Fig. 1.

Columns: the inputs, srcML's markup (srcML for Python, our front ends for OpenQASM), the quantum layer E1 to E5 with
srcSlice, and what the developer is shown. Every part carries one line of the running example, computed here from the
tool, srcML and the committed slice of q[4] (results/icpc/b_example/teleport_chain_q4.json), never typed by hand.
Box fills say where a part comes from: white is taken unchanged, light grey is extended, dark is new; they stay
distinct in greyscale.
Usage (from the workspace root): python paper/figures/src/make_fig_b_architecture.py -> paper/figures/src/fig_b_architecture.tex
"""
import json
import re
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent
ROOT = SRC.parents[2]
sys.path.insert(0, str(ROOT))
from tool import srcml as X  # noqa: E402
from tool.interp import trace_file  # noqa: E402
from tool.profile import qubit_arg_texts, slice_profile  # noqa: E402
from tool.quantum_markup import markup  # noqa: E402

PROG = ROOT / "tool" / "tests" / "big" / "teleport_chain.py"
FACTS = ROOT / "experiments" / "results" / "icpc" / "b_example" / "teleport_chain_q4.json"
LINE = 14          # qc.cx(q[src], q[a])
ITER = 1           # the iteration whose operation the trace example shows
TARGET = 4         # the criterion, q[4]


def ranges(xs):
    xs, out = sorted(set(xs)), []
    for x in xs:
        if out and x == out[-1][1] + 1:
            out[-1][1] = x
        else:
            out.append([x, x])
    return ", ".join(str(a) if a == b else f"{a}--{b}" for a, b in out)


def tt(s):
    return r"\texttt{" + s.replace("\\", r"\textbackslash{}").replace("_", r"\_").replace("{", r"\{").replace("}", r"\}") \
        .replace("<", r"\textless{}").replace(">", r"\textgreater{}").replace('"', r"\textquotedbl{}") + "}"


def facts():
    f = json.load(open(FACTS))
    sl = next(s for s in f["slices"] if s["criterion"] == [TARGET])
    src_line = PROG.read_text().splitlines()[LINE - 1]
    col = len(src_line) - len(src_line.lstrip()) + 1
    unit = X.parse_file(PROG)
    call = next(c for c in unit.iter(X.S + "call") if X.line(c) == LINE)
    pos = call.get("{%s}start" % X.POS)
    circ = trace_file(PROG).main_circuit()
    op = next(o for o in circ.ops if o.line == LINE and o.iters and o.iters[-1][1] == ITER)
    qs = [next(iter(s)) for s in op.qubits]
    prof = slice_profile(circ, TARGET, qubit_arg_texts(PROG))
    qm, _ = markup(PROG)
    mcall = next(c for c in qm.iter(X.S + "call") if X.line(c) == LINE)
    A = "{http://www.srcML.org/srcML/quantum}"
    roles = [a.get(A + "arg") for a in mcall.iter(X.S + "argument") if a.get(A + "arg")]
    its = sorted({i for v in sl["iterations"].values() for it in v for _, i in it})
    from tool import srcslice as S
    ss = next(p for p in S.profiles(PROG)[0] if p.var == "src" and p.fn == "GLOBAL")
    assert sl["operations"] == 22 and sl["of"] == 34, "the slice of q[4] changed: check the caption"
    return {
        "code": src_line.strip(), "line": LINE, "pos": pos, "col": col,
        "roles": roles, "gate": op.name, "qs": qs, "iter": ITER, "ops": circ.ops,
        "n_ops": len(circ.ops), "s_ops": sl["operations"], "qlines": ranges(sl["quantum_lines"]),
        "clines": ranges(sl["classical_lines"]), "iters": its,
        "names": sorted(prof.names), "deps": len(prof.dependents),
        "ss_defs": ranges(ss.defs).replace("--", "-"),
        "qu": f'qu:role="{mcall.get(A + "role")}" qu:gate="{mcall.get(A + "gate")}" qu:ops="{mcall.get(A + "ops")}"',
    }


