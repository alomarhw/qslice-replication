"""Fig. 2: the architecture of the approach, with what each part produces on the program of Fig. 1.

Columns: the inputs, srcML's markup (srcML for Python, our front ends for OpenQASM), the quantum layer E1 to E5 with
srcSlice, and what the developer is shown. Every part carries one line of the running example, computed here from the
tool, srcML and the committed slice of q[4] (results/icpc/b_example/teleport_chain_q4.json), never typed by hand.
Box fills say where a part comes from: white is taken unchanged, light grey is extended, dark is new; they stay
distinct in greyscale.
Usage (from the workspace root): python paper/figures/src/make_fig_b_architecture.py -> paper/figures/src/fig_b_architecture.tex
"""
import json
import re
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent
ROOT = SRC.parents[2]
sys.path.insert(0, str(ROOT))
from tool import srcml as X  # noqa: E402
from tool.interp import trace_file  # noqa: E402
from tool.profile import qubit_arg_texts, slice_profile  # noqa: E402
from tool.quantum_markup import markup  # noqa: E402

PROG = ROOT / "tool" / "tests" / "big" / "teleport_chain.py"
FACTS = ROOT / "experiments" / "results" / "icpc" / "b_example" / "teleport_chain_q4.json"
LINE = 14          # qc.cx(q[src], q[a])
ITER = 1           # the iteration whose operation the trace example shows
TARGET = 4         # the criterion, q[4]


def ranges(xs):
    xs, out = sorted(set(xs)), []
    for x in xs:
        if out and x == out[-1][1] + 1:
            out[-1][1] = x
        else:
            out.append([x, x])
    return ", ".join(str(a) if a == b else f"{a}--{b}" for a, b in out)


def tt(s):
    return r"\texttt{" + s.replace("\\", r"\textbackslash{}").replace("_", r"\_").replace("{", r"\{").replace("}", r"\}") \
        .replace("<", r"\textless{}").replace(">", r"\textgreater{}").replace('"', r"\textquotedbl{}") + "}"


def facts():
    f = json.load(open(FACTS))
    sl = next(s for s in f["slices"] if s["criterion"] == [TARGET])
    src_line = PROG.read_text().splitlines()[LINE - 1]
    col = len(src_line) - len(src_line.lstrip()) + 1
    unit = X.parse_file(PROG)
    call = next(c for c in unit.iter(X.S + "call") if X.line(c) == LINE)
    pos = call.get("{%s}start" % X.POS)
    circ = trace_file(PROG).main_circuit()
    op = next(o for o in circ.ops if o.line == LINE and o.iters and o.iters[-1][1] == ITER)
    qs = [next(iter(s)) for s in op.qubits]
    prof = slice_profile(circ, TARGET, qubit_arg_texts(PROG))
    qm, _ = markup(PROG)
    mcall = next(c for c in qm.iter(X.S + "call") if X.line(c) == LINE)
    A = "{http://www.srcML.org/srcML/quantum}"
    roles = [a.get(A + "arg") for a in mcall.iter(X.S + "argument") if a.get(A + "arg")]
    its = sorted({i for v in sl["iterations"].values() for it in v for _, i in it})
    from tool import srcslice as S
    ss = next(p for p in S.profiles(PROG)[0] if p.var == "src" and p.fn == "GLOBAL")
    assert sl["operations"] == 22 and sl["of"] == 34, "the slice of q[4] changed: check the caption"
    return {
        "code": src_line.strip(), "line": LINE, "pos": pos, "col": col,
        "roles": roles, "gate": op.name, "qs": qs, "iter": ITER, "ops": circ.ops,
        "n_ops": len(circ.ops), "s_ops": sl["operations"], "qlines": ranges(sl["quantum_lines"]),
        "clines": ranges(sl["classical_lines"]), "iters": its,
        "names": sorted(prof.names), "deps": len(prof.dependents),
        "ss_defs": ranges(ss.defs).replace("--", "-"),
        "qu": f'qu:role="{mcall.get(A + "role")}" qu:gate="{mcall.get(A + "gate")}" qu:ops="{mcall.get(A + "ops")}"',
    }


HEAD = r"""% Generated by make_fig_b_architecture.py. Do not edit by hand.
\documentclass[tikz,border=2pt]{standalone}
\usepackage[T1]{fontenc}
\usepackage{newtxtext,newtxmath}
\usepackage[varqu,scaled=0.95]{zi4}
\usetikzlibrary{arrows.meta,positioning,calc,fit,backgrounds}
\definecolor{ink}{HTML}{1F2328}\definecolor{mute}{HTML}{57606A}
\definecolor{newC}{HTML}{24527F}\definecolor{extC}{HTML}{D8DEE4}\definecolor{lane}{HTML}{F3F5F7}
\definecolor{exNew}{HTML}{DCE7F2}
\tikzset{
  >={Stealth[length=4pt,width=3.6pt]},
  box/.style={draw=ink, line width=0.6pt, rounded corners=2pt, align=center, inner sep=3pt,
              font=\fontsize{7.6}{9}\selectfont, text=ink, minimum height=1.85cm, anchor=center},
  reused/.style={box, fill=white},
  ext/.style={box, fill=extC},
  new/.style={box, fill=newC, text=white, draw=newC},
  io/.style={box, dashed, fill=white},
  arr/.style={->, line width=0.7pt, draw=ink},
  lab/.style={font=\fontsize{6.6}{7.5}\selectfont\itshape, text=mute, inner sep=1pt},
  lanet/.style={font=\fontsize{8}{9}\selectfont\bfseries, text=mute, anchor=north},
  key/.style={font=\fontsize{7.4}{9}\selectfont, text=ink, anchor=west},
}
% a box: title, what it does, and the running example on a strip
\newcommand{\bx}[3]{\textbf{#1}\\[1pt]{#2}\\[3pt]\setlength{\fboxsep}{2pt}\colorbox{white}{\parbox{\dimexpr\linewidth-4pt\relax}{\centering\color{ink}\fontsize{6.6}{8}\selectfont #3}}}
\newcommand{\bxn}[3]{\textbf{#1}\\[1pt]{#2}\\[3pt]\setlength{\fboxsep}{2pt}\colorbox{exNew}{\parbox{\dimexpr\linewidth-4pt\relax}{\centering\color{ink}\fontsize{6.6}{8}\selectfont #3}}}
\begin{document}
\begin{tikzpicture}
"""


def body(F):
    q0, q1 = F["qs"]
    it = F["iters"]
    iters = f"$h={it[0]}$" + (f"--{it[-1]}" if len(it) > 1 else "")
    rows = []
    a = rows.append
    # columns (x of centres) and rows (y)
    x = {"in": 1.15, "mk": 4.05, "e1": 7.2, "e2": 10.35, "e3": 13.5, "out": 16.85}
    y = {"top": 0.0, "mid": -2.55, "low": -5.1}
    W = {"in": 2.05, "mk": 2.7, "e": 2.8, "out": 2.95}
    def node(style, name, col, row, w, text):
        a(rf"\node[{style}, text width={w}cm] ({name}) at ({x[col]},{y[row]}) {{{text}}};")
    # inputs
    node("io", "qasm", "in", "top", W["in"], r"\bx{OpenQASM 2, 3}{\texttt{.qasm} file}{" + tt("cx q[0],q[1];") + "}")
    node("io", "py", "in", "mid", W["in"], r"\bx{Qiskit}{\texttt{.py} program}{" + tt(F["code"]) + "}")
    # markup
    node("new", "fe", "mk", "top", W["mk"], r"\bxn{Front ends}{OpenQASM~2 and~3 to srcML, with positions}{"
         + tt('<argument_list type="quantum">') + "}")
    node("reused", "srcml", "mk", "mid", W["mk"], r"\bx{srcML}{Python markup with positions}{"
         + tt(f'<call pos:start="{F["pos"]}">') + "}")
    node("ext", "ss", "mk", "low", W["mk"], r"\bx{srcSlice, patched}{def, use, dvars, cfuncs of each variable}{"
         + tt("src") + f": def {F['ss_defs']}" + "}")
    # quantum layer
    node("new", "e1", "e1", "mid", W["e"], r"\bxn{E1 Roles}{what each call does to which qubits}{"
         + tt(f"cx({', '.join(F['roles'])})") + "}")
    node("new", "e2", "e2", "mid", W["e"], r"\bxn{E2 Trace}{the circuit, built without running}{"
         + f"line {F['line']}, $h={F['iter']}$: " + tt(f"cx q{q0}, q{q1}") + "}")
    node("new", "e3", "e3", "mid", W["e"], r"\bxn{E3 Slice}{light cone through measured bits and loops}{"
         + tt("q[4]") + f": {F['s_ops']} of {F['n_ops']} operations" + "}")
    node("new", "e4", "e3", "low", W["e"], r"\bxn{E4 Classical lines}{srcSlice's closure from the slice's lines}{"
         + tt("src = b") + ", line 22}")
    node("new", "e5", "e3", "top", W["e"], r"\bxn{E5 Profile}{uses, names and dependents of a qubit}{"
         + ", ".join(tt(n) for n in F["names"]) + "}")
    node("io", "qm", "e2", "top", W["e"], r"\bx{Quantum markup}{srcML with the layer's roles, for srcML tools}{"
         + tt(F["qu"].split(" qu:ops")[0]) + "}")
    # what is shown
    node("io", "o1", "out", "top", W["out"], r"\bx{Qubit profiles}{" + tt("q[4]") + f" depends on {F['deps']} qubits}}"
         + "{names " + ", ".join(tt(n) for n in F["names"]) + "}")
    node("io", "o2", "out", "mid", W["out"], r"\bx{Slice}{source lines and iterations}{lines " + F["qlines"]
         + "; " + iters + "}")
    node("io", "o3", "out", "low", W["out"], r"\bx{Classical lines}{the statements that set the qubits}{lines "
         + F["clines"] + "}")
    # lanes behind the columns, titled above
    top, bot = y["top"] + 1.12, y["low"] - 1.12
    a(r"\begin{scope}[on background layer]")
    for left, right, title in (("in", "in", "Input"), ("mk", "mk", "Markup"), ("e1", "e3", "Quantum layer"),
                               ("out", "out", "Shown to the developer")):
        wl = W["e"] if left.startswith("e") else W[left]
        wr = W["e"] if right.startswith("e") else W[right]
        x1, x2 = x[left] - wl / 2 - 0.2, x[right] + wr / 2 + 0.2
        a(rf"\fill[lane, rounded corners=3pt] ({x1:.3f},{top:.3f}) rectangle ({x2:.3f},{bot:.3f});")
        a(rf"\node[lanet] at ({(x1 + x2) / 2:.3f},{top + 0.42:.3f}) {{{title}}};")
    a(r"\end{scope}")
    # arrows, with what flows along them
    a(r"\draw[arr] (qasm) -- (fe);")
    a(r"\draw[arr] (py) -- (srcml);")
    a(r"\draw[arr] (srcml) -- (e1);")
    a(r"\draw[arr] (fe.east) -| node[lab, pos=0.25, above] {markup} ([xshift=-0.55cm]e1.north);")
    a(r"\draw[arr] (e1) -- (e2);")
    a(r"\draw[arr] (e2) -- (e3);")
    a(r"\draw[arr] ([xshift=0.55cm]e1.north) |- (qm.west);")
    a(r"\draw[arr] ([xshift=0.25cm]e2.north) -- ([xshift=0.25cm]qm.south);")
    a(r"\draw[arr] (e3) -- (e5);")
    a(r"\draw[arr] (e3) -- node[lab, right] {quantum lines} (e4);")
    a(r"\draw[arr] (srcml) -- (ss);")
    a(r"\draw[arr] (ss) -- node[lab, above] {profiles} (e4);")
    a(r"\draw[arr] (e5) -- (o1);")
    a(r"\draw[arr] (e3) -- (o2);")
    a(r"\draw[arr] (e4) -- (o3);")
    # key
    ky = y["low"] - 1.55
    a(rf"\node[reused, minimum height=0.3cm, minimum width=0.55cm, inner sep=0pt, text width={{}}] (k1) at (0.3,{ky}) {{}};")
    a(r"\node[key, right=0.1cm of k1] (t1) {taken unchanged};")
    a(r"\node[ext, minimum height=0.3cm, minimum width=0.55cm, inner sep=0pt, right=0.35cm of t1] (k2) {};")
    a(r"\node[key, right=0.1cm of k2] (t2) {extended and fixed};")
    a(r"\node[new, minimum height=0.3cm, minimum width=0.55cm, inner sep=0pt, right=0.35cm of t2] (k3) {};")
    a(r"\node[key, right=0.1cm of k3] (t3) {new};")
    a(r"\node[io, minimum height=0.3cm, minimum width=0.55cm, inner sep=0pt, right=0.35cm of t3] (k4) {};")
    a(r"\node[key, right=0.1cm of k4] (t4) {input or output};")
    a(r"\node[key, right=0.5cm of t4] {each part shows its result on the program of Fig.~1, for \texttt{q[4]}};")
    return "\n".join(rows)


def main():
    F = facts()
    (SRC / "fig_b_architecture.tex").write_text(HEAD + body(F) + "\n\\end{tikzpicture}\n\\end{document}\n")
    print("wrote fig_b_architecture.tex")


if __name__ == "__main__":
    main()
