def rw_rule(qc, rule):
    """(reads, writes) per instruction: 'du' (data, no bits), 'cpdg' (data + control), 'wire'."""
    if rule in ("cpdg", "wire"):
        return M.rw(qc, rule)
    out = []
    for inst in qc.data:
        op = inst.operation
        qs = [qc.find_bit(q).index for q in inst.qubits]
        nc = int(getattr(op, "num_ctrl_qubits", 0) or 0)
        r = {("q", x) for x in qs}
        w = {("q", x) for x in qs[nc:]} if nc and len(qs) > nc else set(r)
        out.append((r, w))
    return out


def rule_edges(qc, rule):
    R = rw_rule(qc, rule)
    E, last = set(), {}
    for j, (r, w) in enumerate(R):
        for loc in r:
            if loc in last:
                E.add((last[loc], j, "control" if loc[0] == "c" else "data"))
        for loc in w:
            last[loc] = j
    return E


def seed(qc, rule, t):
    R = rw_rule(qc, rule)
    return max(k for k, (_, w) in enumerate(R) if ("q", t) in w)


def label(qc, lines, k, iters):
    inst = qc.data[k]
    op = inst.operation
    qs = [qc.find_bit(x).index for x in inst.qubits]
    if op.name == "if_else":
        bit = qc.find_bit(op.condition[0]).index
        txt = rf"if c{bit}:{op.blocks[0].data[0].operation.name} q{qs[0]}"
    elif op.name == "measure":
        txt = rf"measure q{qs[0]}\,\textrightarrow\,c{qc.find_bit(inst.clbits[0]).index}"
    else:
        par = f"({float(op.params[0]):.2f})" if op.params else ""
        txt = f"{op.name}{par} " + ",".join(f"q{q}" for q in qs)
    sub = f"line {lines[k]}" + (f", iter {iters[k]}" if iters[k] is not None else "")
    return txt, sub


def layout(n, edges, sx, sy):
    dot = ["digraph G { graph [rankdir=TB, nodesep=0.08, ranksep=0.16]; node [shape=box, width=0.74, height=0.26, fixedsize=true];"]
    dot += [f"n{k};" for k in range(n)]
    dot += [f"n{i} -> n{j};" for i, j in sorted({(i, j) for i, j, _ in edges})]
    dot.append("}")
    plain = subprocess.run(["dot", "-Tplain"], input="\n".join(dot), capture_output=True, text=True, check=True).stdout
    pos = {}
    for ln in plain.splitlines():
        p = ln.split()
        if p and p[0] == "node":
            pos[int(p[1][1:])] = (float(p[2]) * 2.54 * sx, float(p[3]) * 2.54 * sy)   # inches -> cm
    return pos


def panel(qc, lines, iters, pos, edges, missing, style, crit, title, note, dx):
    """style: node index -> 'insl' | 'missdep' | 'entx' (default 'op')."""
    out = [r"\begin{scope}[xshift=%.3fcm]" % dx]
    for k in range(len(qc.data)):
        txt, sub = label(qc, lines, k, iters)
        sty = style.get(k, "op") + (",crit" if k == crit else "")
        out.append(rf"\node[{sty}] (m{k}) at ({pos[k][0]:.3f},{pos[k][1]:.3f}) {{{txt}\\[-1pt]{{\rmfamily\itshape\fontsize{{5}}{{5.5}}\selectfont {sub}}}}};")
    for i, j, kind in sorted(edges):
        out.append(rf"\draw[{kind}E] (m{i}) -- (m{j});")
    for i, j in sorted(missing):
        out.append(rf"\draw[missingE] (m{i}) -- (m{j});")
    xs = [p[0] for p in pos.values()]
    ys = [p[1] for p in pos.values()]
    cx = (min(xs) + max(xs)) / 2
    out.append(rf"\node[ttl] at ({cx:.3f},{max(ys) + 0.36:.3f}) {{{title}}};")
    out.append(rf"\node[note] at ({cx:.3f},{min(ys) - 0.34:.3f}) {{{note}}};")
    out.append(r"\end{scope}")
    return "\n".join(out), max(xs) - min(xs)


def iterations(qc, lines, loop_lines):
    """Loop iteration of each instruction: occurrence index per (line, qubits) when the line is in a loop."""
    seen, it = {}, []
    for k, inst in enumerate(qc.data):
        if lines[k] in loop_lines:
            key = (lines[k], tuple(qc.find_bit(x).index for x in inst.qubits))
            seen[key] = seen.get(key, -1) + 1
            it.append(seen[key])
        else:
            it.append(None)
    return it


def load(prog, key):
    qc, lines = M.build(prog)
    F = json.load(open(SRC / "fig_programs_facts.json"))[key]
    sl = {"du": set(F["slices"]["du"]), "cpdg": set(F["slices"]["cpdg"]), "wire": set(F["slices"]["lc"]),
          "yz": set(F["slices"]["yz"])}
    f = {"du": F["fidelity"]["du"], "cpdg": F["fidelity"]["cpdg"], "wire": F["fidelity"]["lc"]}
    return qc, lines, set(F["dep"]), sl, f


def check(qc, t, rule, E, sl):
    assert M.back(len(qc.data), E, {seed(qc, rule, t)}) == sl[rule], (rule, "drawn graph != study slicer")


def listing(prog, first, last, width, tag):
    """Listing of the program's lines first..last. Trailing comments are dropped in a display copy, so line
    numbers stay those of programs/<prog>; the program itself is untouched."""
    import re
    disp = SRC / "programs" / "_display"
    disp.mkdir(exist_ok=True)
    src = (SRC / "programs" / prog).read_text().splitlines()
    (disp / prog).write_text("\n".join(re.sub(r"\s+#.*$", "", ln) for ln in src) + "\n")
    prog = "_display/" + prog
    return (rf"\begin{{minipage}}[t]{{{width}}}\vspace{{0pt}}{{\footnotesize\textbf{{{tag}}}}}\\[3pt]"
            rf"\lstinputlisting[style=qiskit,firstline={first},lastline={last},firstnumber={first}]{{programs/{prog}}}\end{{minipage}}")


LEGEND = {"data": r"\tikz\draw[dataE](0,0)--(0.45,0); data",
          "control": r"\tikz\draw[controlE](0,0)--(0.45,0); control",
          "quantum": r"\tikz\draw[quantumE](0,0)--(0.45,0); quantum",
          "missing": r"\tikz\draw[missingE](0,0)--(0.45,0); quantum edge missing from the classical PDG",
          "slice": r"\tikz\node[insl,minimum width=4mm,minimum height=2.4mm]{}; in the slice",
          "missed": r"\tikz\node[missdep,minimum width=4mm,minimum height=2.4mm]{}; dependence the slice misses",
          "missed_du": r"\tikz\node[missdepsl,minimum width=4mm,minimum height=2.4mm]{}; in the slice, missed by def-use",
          "entx": r"\tikz\node[entx,minimum width=4mm,minimum height=2.4mm]{}; added by entanglement closure, not a dependence",
          "crit": r"\tikz\node[op,crit,minimum width=4mm,minimum height=2.4mm]{}; last write to the criterion"}


def legend(items):
    return r"{\scriptsize " + r"\hspace{0.9em} ".join(r"\mbox{" + LEGEND[i] + "}" for i in items) + "}"


def ansatz():
    t = 0
    qc, lines, dep, sl, f = load("ansatz.py", "ansatz")
    El = rule_edges(qc, "cpdg")
    cp = {(i, j) for i, j, _ in El}
    Er = {(i, j, k if k == "control" or (i, j) in cp else "quantum") for i, j, k in rule_edges(qc, "wire")}
    check(qc, t, "cpdg", El, sl)
    check(qc, t, "wire", Er, sl)
    assert sl["wire"] == dep, "wire slice should equal the dependences"
    ent = sl["yz"] - sl["wire"]
    assert ent and not (ent & dep), "entanglement-closure extras must be non-dependences"
    missing = {(i, j) for i, j, _ in Er} - cp
    pos = layout(len(qc.data), El | Er, 0.80, 0.80)
    iters = iterations(qc, lines, {12, 13, 15})
    n = len(qc.data)
    sty_l = {k: "insl" for k in sl["cpdg"]} | {k: "missdep" for k in dep - sl["cpdg"]}
    sty_r = {k: "insl" for k in sl["wire"]} | {k: "entx" for k in ent}
    nl = rf"slice of $q_{t}$: {len(sl['cpdg'])} of {n} operations\\fidelity {f['cpdg']:.2f}, misses {len(dep - sl['cpdg'])} dependences"
    nr = rf"slice of $q_{t}$: {len(sl['wire'])} of {n} operations\\fidelity {f['wire']:.2f}, exactly the dependences"
    pl, w = panel(qc, lines, iters, pos, El, missing, sty_l, seed(qc, "cpdg", t), r"(b) Classical PDG", nl, 0.0)
    pr, _ = panel(qc, lines, iters, pos, Er, set(), sty_r, seed(qc, "wire", t), r"(c) Wire rule", nr, w + 2.15)
    tex = (TEX_HEAD + r"\begin{minipage}{17.6cm}" + listing("ansatz.py", 4, 15, "6.55cm", "(a) VQE ansatz") +
           r"\hfill\begin{minipage}[t]{10.95cm}\vspace{0pt}\centering\begin{tikzpicture}" + "\n" + pl + "\n" + pr + "\n" +
           r"\end{tikzpicture}\end{minipage}\\[4pt]\centering" +
           legend(["data", "quantum", "missing", "slice", "missed", "entx", "crit"]) + r"\end{minipage}\end{document}" + "\n")
    (SRC / "fig_pdg_ansatz.tex").write_text(tex)
    return {"missing": sorted(missing), "cpdg": sorted(sl["cpdg"]), "wire": sorted(sl["wire"]), "entx": sorted(ent),
            "panel_width_cm": round(w, 2)}


def teleport():
    t = 2
    qc, lines, dep, sl, f = load("teleport.py", "teleport")
    E = rule_edges(qc, "cpdg")
    Edu = {e for e in E if e[2] != "control"}
    check(qc, t, "cpdg", E, sl)
    check(qc, t, "du", Edu, sl)
    assert rule_edges(qc, "du") == Edu, "def-use should be the classical PDG without control edges"
    pos = layout(len(qc.data), E, 0.78, 0.80)
    n = len(qc.data)
    sty = {k: "insl" for k in sl["cpdg"]} | {k: "missdepsl" for k in dep - sl["du"]}
    note = (rf"slice of $q_{t}$: {len(sl['cpdg'])} of {n}, $F = {f['cpdg']:.2f}$\\"
            rf"def-use: {len(sl['du'])} of {n}, $F = {f['du']:.2f}$")
    p, w = panel(qc, lines, [None] * n, pos, E, set(), sty, seed(qc, "cpdg", t), r"(b) Classical PDG", note, 0.0)
    tex = (TEX_HEAD + r"\begin{minipage}{8.7cm}" + listing("teleport.py", 7, 17, "3.55cm", "(a) Teleportation") +
           r"\hfill\begin{minipage}[t]{5.05cm}\vspace{0pt}\centering\begin{tikzpicture}" + "\n" + p + "\n" +
           r"\end{tikzpicture}\end{minipage}\\[4pt]\centering" + legend(["data", "control", "slice"]) + r"\\[1pt]" +
           legend(["missed_du", "crit"]) + r"\end{minipage}\end{document}" + "\n")
    (SRC / "fig_pdg_teleport.tex").write_text(tex)
    return {"cpdg": sorted(sl["cpdg"]), "du": sorted(sl["du"]), "panel_width_cm": round(w, 2)}


def main():
    print(json.dumps({"ansatz": ansatz(), "teleport": teleport()}))


if __name__ == "__main__":
    main()
