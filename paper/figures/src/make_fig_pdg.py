def ansatz_horizontal():
    """One graph for all four rules on the ansatz, laid out like its circuit: time left to right, a row per
    qubit, a box per layer of the outer loop. The slices are nested (asserted), so a node is shaded by the
    weakest rule that keeps it. Edges are the QDG's (data shared with the classical PDG, quantum, control)
    plus the classical PDG's own edges, each of which skips a CNOT whose control it reads as unchanged."""
    A = ansatz_facts()
    t, qc, lines, dep, sl, f = A["t"], A["qc"], A["lines"], A["dep"], A["sl"], A["f"]
    Er, ent, only_cp, iters, n, T = A["Er"], A["ent"], A["only_cp"], A["iters"], A["n"], A["T"]

    # ---- positions: circuit order, a row per qubit
    CW, RH, BOXGAP = 0.95, 0.62, 0.45
    col = {"ry": 0, "rz": 1}
    pos = {}
    for k in range(n):
        inst = qc.data[k]
        qs = [qc.find_bit(x).index for x in inst.qubits]
        if iters[k] is not None:
            c = col.get(inst.operation.name, 2 + qs[0])  # cx(0,1) -> 2, cx(1,2) -> 3
            pos[k] = (iters[k] * (4 * CW + BOXGAP) + c * CW, -sum(qs) / len(qs) * RH)
    XD = 2 * (4 * CW + BOXGAP) + 0.2
    aux = [k for k in range(n) if iters[k] is None]
    assert [qc.data[k].operation.name for k in aux] == ["h", "measure", "if_else"]
    pos[aux[0]] = (XD, -3 * RH)
    pos[aux[1]] = (XD + 1.25, -3 * RH)
    pos[aux[2]] = (XD + 2.3, 0.0)

    level, crit = A["level"], A["crit"]
    o = []
    for k in range(n):
        inst = qc.data[k]
        op = inst.operation
        qs = [qc.find_bit(x).index for x in inst.qubits]
        if op.name == "if_else":
            txt, sub = rf"if c{qc.find_bit(op.condition[0]).index}: x q{qs[0]}", f"lines {lines[k]}--{lines[k] + 1}"
        elif op.name == "measure":
            txt, sub = rf"measure q{qs[0]}\,\textrightarrow\,c{qc.find_bit(inst.clbits[0]).index}", f"line {lines[k]}"
        else:
            txt, sub = f"{op.name} " + ",".join(f"q{q}" for q in qs), f"line {lines[k]}"
        sty = level.get(k, "op") + (",crit" if k == crit else "")
        o.append(rf"\node[{sty}] (m{k}) at ({pos[k][0]:.3f},{pos[k][1]:.3f}) {{{txt}\\[-1pt]{{\rmfamily\itshape\fontsize{{5}}{{5.5}}\selectfont {sub}}}}};")
    for i, j, kind in sorted(Er):
        o.append(rf"\draw[{kind}E] (m{i}) -- (m{j});")
    for i, j in sorted(only_cp):
        o.append(rf"\draw[cpdgE] (m{i}) to[bend left=14] (m{j});")

    # ---- loop boxes and classical statements (shaded when the tool puts their line in the QDG slice)
    cls = T["wire"]["classical"]
    def csty(ln):
        return "clq" if ln in cls else "cl"
    btop, bbot = 0.62, -2 * RH - 0.32
    boxes = {}
    for L in range(2):
        x0 = L * (4 * CW + BOXGAP) - 0.5
        x1 = L * (4 * CW + BOXGAP) + 3 * CW + 0.5
        boxes[L] = (x0, x1)
        o.append(rf"\draw[loopbox] ({x0:.3f},{bbot:.3f}) rectangle ({x1:.3f},{btop:.3f});")
        o.append(rf"\node[boxlbl, anchor=south west] at ({x0 + 0.02:.3f},{btop + 0.01:.3f}) {{layer = {L}}};")
        for ln, cx_ in ((11, L * (4 * CW + BOXGAP) + 0.5 * CW), (14, L * (4 * CW + BOXGAP) + 2.5 * CW)):
            o.append(rf"\node[{csty(ln)}, inner ysep=0.6pt] at ({cx_:.3f},{btop - 0.2:.3f}) "
                     rf"{{for qubit\,{{\rmfamily\itshape\fontsize{{5}}{{5.5}}\selectfont (line {ln})}}}};")
    yA, yB = btop + 1.05, btop + 0.5
    row = [("ly", 5, "layers = 2", (0.45, yA)), ("n", 4, "n = 3", (1.85, yA)),
           ("qc", 8, "qc = QuantumCircuit(n + 1, n + 1)", (3.95, yA)), ("rng", 6, r"rng = default\_rng(7)", (7.05, yA)),
           ("for", 10, "for layer in range(layers)", (1.45, yB))]
    for key, ln, txt, (x, y) in row:
        o.append(rf"\node[{csty(ln)}] (c{key}) at ({x:.3f},{y:.3f}) {{{txt}\\[-1pt]{{\rmfamily\itshape\fontsize{{5}}{{5.5}}\selectfont line {ln}}}}};")
    o.append(r"\draw[dataE] (cn) -- (cqc);")
    o.append(r"\draw[dataE] (cly) -- (cfor);")
    into = {("for", 0): (0.55, "control"), ("for", 1): (4.45, "control"), ("qc", 0): (2.55, "data"),
            ("qc", 1): (5.0, "data"), ("rng", 0): (2.95, "data"), ("rng", 1): (7.2, "data")}
    for (key, L), (x, kind) in into.items():
        assert boxes[L][0] < x < boxes[L][1]
        o.append(rf"\draw[{kind}E] (c{key}) -- ({x:.3f},{btop:.3f});")

    # ---- the four slices, one line under the graph
    note = (rf"slices of $q_{t}$, of {n} operations:\enspace def-use {len(sl['du'])}, $F = {f['du']:.2f}$\enspace"
            rf"$\cdot$\enspace classical PDG {len(sl['cpdg'])}, $F = {f['cpdg']:.2f}$\\"
            rf"QDG {len(sl['wire'])}, exactly the dependences, $F = {f['wire']:.2f}$\enspace$\cdot$\enspace{{}}"
            rf"QPDG {len(sl['yz'])}, $F = {f['yz']:.2f}$")
    xmid = (boxes[0][0] + XD + 2.9) / 2
    o.append(rf"\node[font=\scriptsize, anchor=north, align=center] (note) at ({xmid:.3f},{-3 * RH - 0.36:.3f}) {{{note}}};")
    leg = (legend(["data", "quantumq", "cpdgonly"]) + r"\\[2pt]" + legend(["control", "crit", "loop"]) + r"\\[2pt]"
           + legend(["lvdu", "lvcp", "lvqd"]) + r"\\[2pt]" + legend(["lvyz", "classicalq"]))
    o.append(rf"\node[anchor=north, align=center] at ($(note.south)+(0,-0.08)$) {{{leg}}};")
    graph = "\n".join(o)
    tex = (TEX_HEAD + r"\begin{minipage}{17.8cm}" + listing("ansatz.py", 4, 20, "5.5cm", "(a) VQE ansatz") +
           r"\hfill\begin{minipage}[t]{12.2cm}\vspace{0pt}\centering{\footnotesize\textbf{(b) Dependence graph of the four rules, criterion $q_0$}}\\[4pt]"
           r"\begin{tikzpicture}" + "\n" + graph + "\n" + r"\end{tikzpicture}\end{minipage}\end{minipage}\end{document}" + "\n")
    (SRC / "fig_pdg_ansatz.tex").write_text(tex)
    return {"quantum": sorted((i, j) for i, j, k in Er if k == "quantum"), "cpdg_only": sorted(only_cp),
            "du": sorted(sl["du"]), "cpdg": sorted(sl["cpdg"]), "wire": sorted(sl["wire"]), "entx": sorted(ent)}


