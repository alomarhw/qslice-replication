def rw_rule(qc, rule):
    """(reads, writes) per instruction: 'du' (data, no bits), 'cpdg' (data + control), 'wire'."""
    if rule in ("cpdg", "wire"):
        return M.rw(qc, rule)
    out = []
    for inst in qc.data:
        op = inst.operation
        qs = [qc.find_bit(q).index for q in inst.qubits]
        nc = int(getattr(op, "num_ctrl_qubits", 0) or 0)
        r = {("q", x) for x in qs}
        w = {("q", x) for x in qs[nc:]} if nc and len(qs) > nc else set(r)
        out.append((r, w))
    return out


def rule_edges(qc, rule):
    R = rw_rule(qc, rule)
    E, last = set(), {}
    for j, (r, w) in enumerate(R):
        for loc in r:
            if loc in last:
                E.add((last[loc], j, "control" if loc[0] == "c" else "data"))
        for loc in w:
            last[loc] = j
    return E


def seed(qc, rule, t):
    R = rw_rule(qc, rule)
    return max(k for k, (_, w) in enumerate(R) if ("q", t) in w)


def label(qc, lines, k, iters):
    inst = qc.data[k]
    op = inst.operation
    qs = [qc.find_bit(x).index for x in inst.qubits]
    if op.name == "if_else":
        bit = qc.find_bit(op.condition[0]).index
        txt = rf"if c{bit}:{op.blocks[0].data[0].operation.name} q{qs[0]}"
    elif op.name == "measure":
        txt = rf"measure q{qs[0]}\,\textrightarrow\,c{qc.find_bit(inst.clbits[0]).index}"
    else:
        par = f"({float(op.params[0]):.2f})" if op.params else ""
        txt = f"{op.name}{par} " + ",".join(f"q{q}" for q in qs)
    ln = f"lines {lines[k]}--{lines[k] + 1}" if op.name == "if_else" else f"line {lines[k]}"  # if_test header and its gate
    sub = ln + (f", iter {iters[k]}" if iters[k] is not None else "")
    return txt, sub


def layout(n, edges, sx, sy, clusters=None):
    """clusters: name -> node indices kept together in one box (a loop iteration)."""
    dot = ["digraph G { graph [rankdir=TB, nodesep=0.08, ranksep=0.16]; node [shape=box, width=0.74, height=0.26, fixedsize=true];"]
    inside = set()
    for c, ks in (clusters or {}).items():
        dot.append(f"subgraph cluster_{c} {{ margin=10; " + " ".join(f"n{k};" for k in ks) + " }")
        inside |= set(ks)
    dot += [f"n{k};" for k in range(n) if k not in inside]
    dot += [f"n{i} -> n{j};" for i, j in sorted({(i, j) for i, j, _ in edges})]
    dot.append("}")
    plain = subprocess.run(["dot", "-Tplain"], input="\n".join(dot), capture_output=True, text=True, check=True).stdout
    pos = {}
    for ln in plain.splitlines():
        p = ln.split()
        if p and p[0] == "node":
            pos[int(p[1][1:])] = (float(p[2]) * 2.54 * sx, float(p[3]) * 2.54 * sy)   # inches -> cm
    return pos


def panel(qc, lines, iters, pos, edges, missing, style, crit, title, note, dx, extra=None):
    """style: node index -> 'insl' | 'missdep' | 'entx' (default 'op'). extra: (tikz, top y) of the program's
    classical statements, drawn above the operations."""
    out = [r"\begin{scope}[xshift=%.3fcm]" % dx]
    for k in range(len(qc.data)):
        txt, sub = label(qc, lines, k, iters)
        sty = style.get(k, "op") + (",crit" if k == crit else "")
        out.append(rf"\node[{sty}] (m{k}) at ({pos[k][0]:.3f},{pos[k][1]:.3f}) {{{txt}\\[-1pt]{{\rmfamily\itshape\fontsize{{5}}{{5.5}}\selectfont {sub}}}}};")
    for i, j, kind in sorted(edges):
        out.append(rf"\draw[{kind}E] (m{i}) -- (m{j});")
    for i, j in sorted(missing):
        out.append(rf"\draw[missingE] (m{i}) -- (m{j});")
    xs = [p[0] for p in pos.values()]
    ys = [p[1] for p in pos.values()]
    cx = (min(xs) + max(xs)) / 2
    top = max(ys) + 0.36
    if extra:
        out.append(extra[0])
        top = extra[1]
    out.append(rf"\node[ttl] at ({cx:.3f},{top:.3f}) {{{title}}};")
    out.append(rf"\node[note] at ({cx:.3f},{min(ys) - 0.34:.3f}) {{{note}}};")
    out.append(r"\end{scope}")
    return "\n".join(out), max(xs) - min(xs)


def classical(pos, boxes, row, edges, slice_lines):
    """The program's classical statements as nodes above the operations, and a box around each loop iteration.
    boxes: name -> (node indices, label, header statements [(line, text)]); row: [(key, line, text, (x, y))] with
    x as a fraction of the panel width and y above the top operation; edges: (from key, to key or box name,
    kind). A statement is shaded when the tool puts its line in the slice."""
    xs = [p[0] for p in pos.values()]
    ys = [p[1] for p in pos.values()]
    x0, w, ytop = min(xs) - 0.62, max(xs) - min(xs) + 1.24, max(ys)
    out, side = [], {}
    for b, (ks, lbl, hdr) in boxes.items():
        bx = [pos[k][0] for k in ks]
        by = [pos[k][1] for k in ks]
        out.append(rf"\draw[loopbox] ({min(bx) - 0.66:.3f},{min(by) - 0.30:.3f}) rectangle ({max(bx) + 0.66:.3f},{max(by) + 0.72:.3f});")
        side[b] = (min(bx) - 0.66, max(bx) + 0.66, max(by) + 0.30)
        out.append(rf"\node[boxlbl, anchor=north west] at ({min(bx) - 0.64:.3f},{max(by) + 0.70:.3f}) {{{lbl}}};")
        for i, (ln, txt) in enumerate(hdr):
            sty = "clsl" if ln in slice_lines else "cl"
            out.append(rf"\node[{sty}, anchor=north east, inner ysep=0.6pt] at ({max(bx) + 0.64 - i * 1.30:.3f},{max(by) + 0.70:.3f}) "
                       rf"{{{txt}\,{{\rmfamily\itshape\fontsize{{5}}{{5.5}}\selectfont {ln}}}}};")
    for key, ln, txt, (fx, fy) in row:
        sty = "clsl" if ln in slice_lines else "cl"
        out.append(rf"\node[{sty}] (c{key}) at ({x0 + fx * w:.3f},{ytop + fy:.3f}) {{{txt}\\[-1pt]{{\rmfamily\itshape\fontsize{{5}}{{5.5}}\selectfont line {ln}}}}};")
    used = {"west": 0, "east": 0}
    for a, b, kind, *how in edges:
        if b not in boxes:
            out.append(rf"\draw[{kind}E] (c{a}) -- (c{b});")
            continue
        # into a loop box from the side, along a lane outside the boxes, so the edge crosses no operation
        lx, rx, y = side[b]
        d = how[0] if how else "west"
        lane = (lx - 0.12 - 0.09 * used[d]) if d == "west" else (rx + 0.12 + 0.09 * used[d])
        used[d] += 1
        out.append(rf"\draw[{kind}E] (c{a}.{d}) -| ({lane:.3f},{y:.3f}) -- ({lx if d == 'west' else rx:.3f},{y:.3f});")
    return "\n".join(out), ytop + max(fy for *_, (_, fy) in row) + 0.30


def iterations(qc, lines, loop_lines):
    """Loop iteration of each instruction: occurrence index per (line, qubits) when the line is in a loop."""
    seen, it = {}, []
    for k, inst in enumerate(qc.data):
        if lines[k] in loop_lines:
            key = (lines[k], tuple(qc.find_bit(x).index for x in inst.qubits))
            seen[key] = seen.get(key, -1) + 1
            it.append(seen[key])
        else:
            it.append(None)
    return it


def load(prog, key):
    qc, lines = M.build(prog)
    F = json.load(open(SRC / "fig_programs_facts.json"))[key]
    sl = {"du": set(F["slices"]["du"]), "cpdg": set(F["slices"]["cpdg"]), "wire": set(F["slices"]["lc"]),
          "yz": set(F["slices"]["yz"])}
    f = {"du": F["fidelity"]["du"], "cpdg": F["fidelity"]["cpdg"], "wire": F["fidelity"]["lc"]}
    return qc, lines, set(F["dep"]), sl, f


def tool_slices(prog, t):
    """The tool's slice of qubit t (static, tool/), under the QDG rule and the classical PDG reading."""
    sys.path.insert(0, str(SRC.parents[2]))
    from tool.interp import trace_file
    from tool.slicer import wire_slice
    c = trace_file(SRC / "programs" / prog).main_circuit()
    out = {}
    for rule in ("wire", "cpdg"):
        s = wire_slice(c, [t], rule=rule)
        out[rule] = {"ops_lines": {c.ops[k].line for k in s.ops}, "classical": set(s.classical_lines)}
    return out


def check(qc, t, rule, E, sl):
    assert M.back(len(qc.data), E, {seed(qc, rule, t)}) == sl[rule], (rule, "drawn graph != study slicer")


def listing(prog, first, last, width, tag, below=""):
    """Listing of the program's lines first..last. Trailing comments are dropped in a display copy, so line
    numbers stay those of programs/<prog>; the program itself is untouched."""
    import re
    disp = SRC / "programs" / "_display"
    disp.mkdir(exist_ok=True)
    src = (SRC / "programs" / prog).read_text().splitlines()
    (disp / prog).write_text("\n".join(re.sub(r"\s+#.*$", "", ln) for ln in src) + "\n")
    prog = "_display/" + prog
    return (rf"\begin{{minipage}}[t]{{{width}}}\vspace{{0pt}}{{\footnotesize\textbf{{{tag}}}}}\\[3pt]"
            rf"\lstinputlisting[style=qiskit,firstline={first},lastline={last},firstnumber={first}]{{programs/{prog}}}{below}\end{{minipage}}")


