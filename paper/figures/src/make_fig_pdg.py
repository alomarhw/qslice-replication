def ansatz_facts():
    """Everything both layouts draw, with the checks against the study's slicers and the tool."""
    t = 0
    qc, lines, dep, sl, f = load("ansatz.py", "ansatz")
    El = rule_edges(qc, "cpdg")
    Edu = {e for e in El if e[2] != "control"}
    assert rule_edges(qc, "du") == Edu, "def-use should be the classical PDG without control edges"
    check(qc, t, "du", Edu, sl)
    cp = {(i, j) for i, j, _ in El}
    Er = {(i, j, k if k == "control" or (i, j) in cp else "quantum") for i, j, k in rule_edges(qc, "wire")}
    check(qc, t, "cpdg", El, sl)
    check(qc, t, "wire", Er, sl)
    assert sl["wire"] == dep, "wire slice should equal the dependences"
    assert sl["du"] < sl["cpdg"] < sl["wire"] < sl["yz"], "the four slices should be nested"
    ent = sl["yz"] - sl["wire"]
    assert ent and not (ent & dep), "entanglement-closure extras must be non-dependences"
    wr = {(i, j) for i, j, _ in Er}
    only_cp = {(i, j) for i, j, _ in El if (i, j) not in wr}
    # each classical-PDG-only edge skips exactly the CNOT that the QDG routes through
    for i, j in only_cp:
        via = [k for k in range(i + 1, j) if (i, k) in wr and (k, j) in wr and qc.data[k].operation.name == "cx"]
        assert len(via) == 1, (i, j, via)
    iters = iterations(qc, lines, {12, 13, 15})
    n = len(qc.data)
    T = tool_slices("ansatz.py", t)
    tl = lambda ks: {lines[k] + (qc.data[k].operation.name == "if_else") for k in ks}  # noqa: E731
    assert T["wire"]["ops_lines"] == tl(sl["wire"]) and T["cpdg"]["ops_lines"] == tl(sl["cpdg"])
    level = ({k: "lvqd" for k in sl["wire"]} | {k: "lvcp" for k in sl["cpdg"]} | {k: "lvdu" for k in sl["du"]}
             | {k: "entx" for k in ent})
    crit = seed(qc, "wire", t)
    assert crit == seed(qc, "cpdg", t) == seed(qc, "du", t)
    note = (rf"slices of $q_{t}$, of {n} operations:\\def-use {len(sl['du'])}, $F = {f['du']:.2f}$\enspace"
            rf"$\cdot$\enspace classical PDG {len(sl['cpdg'])}, $F = {f['cpdg']:.2f}$\\"
            rf"QDG {len(sl['wire'])}, exactly the dependences, $F = {f['wire']:.2f}$\enspace$\cdot$\enspace{{}}"
            rf"QPDG {len(sl['yz'])}, $F = {f['yz']:.2f}$")
    return dict(t=t, qc=qc, lines=lines, dep=dep, sl=sl, f=f, El=El, Er=Er, ent=ent, only_cp=only_cp, iters=iters,
                n=n, T=T, level=level, crit=crit, note=note)


