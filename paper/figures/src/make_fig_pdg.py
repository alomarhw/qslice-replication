def legend_column(items):
    """The legend as a column, for the empty space under a listing."""
    return r"\par\vspace{10pt}{\scriptsize\raggedright " + r"\par\vspace{2.5pt}".join(LEGEND[i] for i in items) + r"\par}"


def legend(items):
    return r"{\scriptsize " + r"\hspace{0.9em} ".join(r"\mbox{" + LEGEND[i] + "}" for i in items) + "}"


def ansatz():
    t = 0
    qc, lines, dep, sl, f = load("ansatz.py", "ansatz")
    El = rule_edges(qc, "cpdg")
    cp = {(i, j) for i, j, _ in El}
    Er = {(i, j, k if k == "control" or (i, j) in cp else "quantum") for i, j, k in rule_edges(qc, "wire")}
    check(qc, t, "cpdg", El, sl)
    check(qc, t, "wire", Er, sl)
    assert sl["wire"] == dep, "wire slice should equal the dependences"
    ent = sl["yz"] - sl["wire"]
    assert ent and not (ent & dep), "entanglement-closure extras must be non-dependences"
    missing = {(i, j) for i, j, _ in Er} - cp
    iters = iterations(qc, lines, {12, 13, 15})
    n = len(qc.data)
    lay = {L: [k for k in range(n) if iters[k] == L] for L in range(2)}
    assert sorted(lay[0] + lay[1]) == [k for k in range(n) if lines[k] in (12, 13, 15)] and all(lines[k] != 17 for k in range(n))
    pos = layout(n, El | Er, 0.80, 0.80, clusters=lay)
    T = tool_slices("ansatz.py", t)
    assert T["wire"]["ops_lines"] == {lines[k] for k in sl["wire"]} and T["cpdg"]["ops_lines"] == {lines[k] for k in sl["cpdg"]}
    boxes = {L: (lay[L], rf"layer = {L}", [(14, "for qubit"), (11, "for qubit")]) for L in lay}
    row = [("n", 4, "n = 3", (0.10, 2.15)), ("ly", 5, "layers = 2", (0.40, 2.15)), ("rng", 6, r"rng = default\_rng(7)", (0.80, 2.15)),
           ("qc", 8, "qc = QuantumCircuit(n, n)", (0.70, 1.60)), ("for", 10, "for layer in range(layers)", (0.27, 1.13))]
    ce = [("n", "qc", "data"), ("ly", "for", "data"), ("for", 0, "control", "west"), ("for", 1, "control", "west"),
          ("rng", 0, "data", "east"), ("rng", 1, "data", "east"), ("qc", 0, "data", "east"), ("qc", 1, "data", "east")]
    xb = classical(pos, boxes, row, ce, T["cpdg"]["classical"])
    xr = classical(pos, boxes, row, ce, T["wire"]["classical"])
    sty_l = {k: "insl" for k in sl["cpdg"]} | {k: "missdep" for k in dep - sl["cpdg"]}
    sty_r = {k: "insl" for k in sl["wire"]} | {k: "entx" for k in ent}
    nl = rf"slice of $q_{t}$: {len(sl['cpdg'])} of {n} operations\\fidelity {f['cpdg']:.2f}, misses {len(dep - sl['cpdg'])} dependences"
    nr = rf"slice of $q_{t}$: {len(sl['wire'])} of {n} operations\\fidelity {f['wire']:.2f}, exactly the dependences"
    pl, w = panel(qc, lines, iters, pos, El, missing, sty_l, seed(qc, "cpdg", t), r"(b) Classical PDG", nl, 0.0, xb)
    pr, _ = panel(qc, lines, iters, pos, Er, set(), sty_r, seed(qc, "wire", t), r"(c) QDG", nr, w + 2.75, xr)
    tex = (TEX_HEAD + r"\begin{minipage}{17.6cm}" + listing("ansatz.py", 4, 15, "6.0cm", "(a) VQE ansatz",
                                      legend_column(["data", "control", "quantum", "missing", "slice", "missed", "entx", "crit", "classical", "loop"])) +
           r"\hfill\begin{minipage}[t]{11.5cm}\vspace{0pt}\centering\begin{tikzpicture}" + "\n" + pl + "\n" + pr + "\n" +
           r"\end{tikzpicture}\end{minipage}\end{minipage}\end{document}" + "\n")
    (SRC / "fig_pdg_ansatz.tex").write_text(tex)
    return {"missing": sorted(missing), "cpdg": sorted(sl["cpdg"]), "wire": sorted(sl["wire"]), "entx": sorted(ent),
            "panel_width_cm": round(w, 2)}


def teleport():
    t = 2
    qc, lines, dep, sl, f = load("teleport.py", "teleport")
    E = rule_edges(qc, "cpdg")
    Edu = {e for e in E if e[2] != "control"}
    check(qc, t, "cpdg", E, sl)
    check(qc, t, "du", Edu, sl)
    assert rule_edges(qc, "du") == Edu, "def-use should be the classical PDG without control edges"
    pos = layout(len(qc.data), E, 0.78, 0.80)
    n = len(qc.data)
    T = tool_slices("teleport.py", t)
    # the tool gives a conditioned gate its own line (15, 17); the figure names the if_test header above it
    assert T["cpdg"]["ops_lines"] == {lines[k] + (qc.data[k].operation.name == "if_else") for k in sl["cpdg"]}
    row = [("q", 3, r"q = QuantumRegister(3, \textquotedbl q\textquotedbl)", (0.30, 1.95)),
           ("c", 4, r"c = ClassicalRegister(2, \textquotedbl c\textquotedbl)", (0.70, 1.40)),
           ("qc", 5, "qc = QuantumCircuit(q, c)", (0.42, 0.85))]
    xt = classical(pos, {}, row, [("q", "qc", "data"), ("c", "qc", "data")], T["cpdg"]["classical"])
    sty = {k: "insl" for k in sl["cpdg"]} | {k: "missdepsl" for k in dep - sl["du"]}
    note = (rf"slice of $q_{t}$: {len(sl['cpdg'])} of {n}, $F = {f['cpdg']:.2f}$\\"
            rf"def-use: {len(sl['du'])} of {n}, $F = {f['du']:.2f}$")
    p, w = panel(qc, lines, [None] * n, pos, E, set(), sty, seed(qc, "cpdg", t), r"(b) Classical PDG", note, 0.0, xt)
    tex = (TEX_HEAD + r"\begin{minipage}{8.7cm}" + listing("teleport.py", 3, 17, "3.55cm", "(a) Teleportation") +
           r"\hfill\begin{minipage}[t]{5.05cm}\vspace{0pt}\centering\begin{tikzpicture}" + "\n" + p + "\n" +
           r"\end{tikzpicture}\end{minipage}\\[4pt]\centering" + legend(["data", "control", "slice"]) + r"\\[1pt]" +
           legend(["missed_du", "crit"]) + r"\\[1pt]" + legend(["classical"]) + r"\end{minipage}\end{document}" + "\n")
    (SRC / "fig_pdg_teleport.tex").write_text(tex)
    return {"cpdg": sorted(sl["cpdg"]), "du": sorted(sl["du"]), "panel_width_cm": round(w, 2)}


def main():
    print(json.dumps({"ansatz": ansatz(), "teleport": teleport()}))


if __name__ == "__main__":
    main()
