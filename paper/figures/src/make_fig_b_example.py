"""Paper B, Fig. 1: the teleportation chain with the slice of q[4] drawn on its lines.

Lines whose operations are in the slice are shaded blue, the classical statements that compute them grey. For each
gate line of the loop, four dots give its operation in hops 0 to 3, filled where that operation is in the slice. The
last column marks the lines of srcSlice's slice of qc, every line that calls a gate on it. Everything comes from the
saved result (results/icpc/b_example/teleport_chain_q4.json) and the program's text, and no tool name appears.
Usage (from the workspace root): python paper/figures/src/make_fig_b_example.py -> paper/figures/src/fig_b_example.tex
"""
import json
import re
from pathlib import Path

SRC = Path(__file__).resolve().parent
ROOT = SRC.parents[2]
PROG = ROOT / "tool" / "tests" / "big" / "teleport_chain.py"
RES = ROOT / "experiments" / "results" / "icpc" / "b_example" / "teleport_chain_q4.json"
FIRST = 3  # the imports on lines 1 and 2 are omitted
KEYWORDS = {"for", "in", "with"}

HEAD = r"""% Generated by make_fig_b_example.py. Do not edit by hand.
\documentclass[tikz,border=1pt]{standalone}
\usepackage[T1]{fontenc}
\usepackage{newtxtext,newtxmath}
\usepackage[varqu,scaled=0.95]{zi4}
\usetikzlibrary{positioning}
\definecolor{ink}{HTML}{1F2328}\definecolor{mute}{HTML}{6E7781}
\definecolor{wire}{HTML}{24527F}\definecolor{qbg}{HTML}{DCE7F3}\definecolor{cbg}{HTML}{EEF0F2}
\definecolor{kw}{HTML}{24527F}\definecolor{str}{HTML}{8A4B08}
\tikzset{
  code/.style={anchor=base west, inner sep=0pt, font=\ttfamily\fontsize{8}{9.6}\selectfont, text=ink},
  num/.style={anchor=base east, inner sep=0pt, font=\ttfamily\fontsize{7}{9.6}\selectfont, text=mute},
  hdr/.style={anchor=base, inner sep=0pt, font=\fontsize{7}{8}\selectfont, text=ink, align=center},
  key/.style={anchor=base west, inner sep=0pt, font=\fontsize{7}{8}\selectfont, text=ink},
}
\begin{document}
\begin{tikzpicture}
"""


def tex_code(line: str) -> str:
    """The line in \\ttfamily, keywords bold and blue, strings brown."""
    out = []
    for tok in re.findall(r'"[^"]*"|\w+|\s+|.', line):
        t = tok.replace("\\", r"\textbackslash{}").replace("_", r"\_").replace("{", r"\{").replace("}", r"\}")
        t = t.replace(" ", r"\ ")
        if tok in KEYWORDS:
            t = r"\textcolor{kw}{\bfseries " + t + "}"
        elif tok.startswith('"'):
            t = r"\textcolor{str}{" + t + "}"
        out.append(t)
    return "".join(out)


def main():
    src = PROG.read_text().splitlines()
    sl = json.load(open(RES))["slices"][0]
    qlines, clines = set(sl["quantum_lines"]), set(sl["classical_lines"])
    hops = {int(k): {it[0][1] for it in v} for k, v in sl["iterations"].items()}
    loop = range(11, 23)
    gate = {i for i, s in enumerate(src, 1) if re.search(r"\bqc\.(?!if_test)\w+\(", s) and i >= FIRST}
    n_hops = 4

    ROW, X0, CODE_W = 0.36, 0.0, 5.9
    XH = CODE_W + 0.35          # first hop dot
    DH = 0.27                   # hop spacing
    XS = XH + 3 * DH + 0.9     # srcSlice column
    o = [HEAD]
    # headers
    o.append(rf"\node[hdr] at ({XH + 1.5 * DH},0.42) {{iteration $h$}};")
    for h in range(n_hops):
        o.append(rf"\node[hdr, text=mute] at ({XH + h * DH},0.12) {{{h}}};")
    o.append(r"\node[hdr, anchor=base west] at (-0.45,0.12) {\bfseries Program, with the slice of \texttt{q[4]}};")
    o.append(rf"\node[hdr] at ({XS},0.42) {{srcSlice}};")
    o.append(rf"\node[hdr, text=mute] at ({XS},0.12) {{\texttt{{qc}}}};")
    o.append(rf"\draw[mute, line width=0.4pt] (-0.45,-0.02) -- ({XS + 0.42},-0.02);")
    for r, i in enumerate(range(FIRST, len(src) + 1)):
        y = -(r + 1) * ROW
        if i in qlines or i in clines:
            fill, bar = ("qbg", "wire") if i in qlines else ("cbg", "mute!70")
            o.append(rf"\fill[{fill}] (-0.45,{y - 0.11:.3f}) rectangle ({CODE_W},{y + 0.25:.3f});")
            o.append(rf"\fill[{bar}] (-0.45,{y - 0.11:.3f}) rectangle (-0.4,{y + 0.25:.3f});")
        o.append(rf"\node[num] at (-0.12,{y:.3f}) {{{i}}};")
        o.append(rf"\node[code] at ({X0},{y:.3f}) {{{tex_code(src[i - 1])}}};")
        if i in loop and i in gate:
            for h in range(n_hops):
                on = h in hops.get(i, set())
                o.append(rf"\draw[wire, line width=0.5pt, fill={'wire' if on else 'white'}] "
                         rf"({XH + h * DH},{y + 0.07:.3f}) circle (0.075);")
        if i in gate:
            o.append(rf"\fill[mute] ({XS - 0.07},{y}) rectangle ++(0.14,0.14);")
    yb = -(len(src) - FIRST + 2) * ROW - 0.05
    o.append(rf"\draw[mute, line width=0.4pt] (-0.45,{yb + 0.3:.3f}) -- ({XS + 0.42},{yb + 0.3:.3f});")
    items = [
        (r"\fill[qbg] (0,0) rectangle (0.32,0.2); \fill[wire] (0,0) rectangle (0.04,0.2);", "operations in the slice of \\texttt{q[4]}"),
        (r"\fill[cbg] (0,0) rectangle (0.32,0.2); \fill[mute!70] (0,0) rectangle (0.04,0.2);", "classical statement that computes them"),
    ]
    items2 = [
        (r"\draw[wire, line width=0.5pt, fill=wire] (0.16,0.07) circle (0.075);", "operation of iteration $h$ in the slice"),
        (r"\draw[wire, line width=0.5pt, fill=white] (0.16,0.07) circle (0.075);", "operation of iteration $h$ left out"),
    ]
    items3 = [(r"\fill[mute] (0.09,0) rectangle ++(0.14,0.14);", "in srcSlice's slice of \\texttt{qc}")]
    for row, its in enumerate((items, items2, items3)):
        x = -0.45
        for sym, label in its:
            o.append(rf"\begin{{scope}}[shift={{({x},{yb - row * 0.32:.3f})}}] {sym} \end{{scope}}")
            o.append(rf"\node[key] (k) at ({x + 0.4},{yb - row * 0.32:.3f}) {{{label}}};")
            x += 0.4 + 0.11 * len(re.sub(r"\\texttt\{([^}]*)\}|\\\w+", lambda m: m.group(1) or "", label)) + 0.35
    o.append(r"\end{tikzpicture}")
    o.append(r"\end{document}")
    (SRC / "fig_b_example.tex").write_text("\n".join(o) + "\n")
    print("wrote fig_b_example.tex | quantum", sorted(qlines), "classical", sorted(clines))


if __name__ == "__main__":
    main()
