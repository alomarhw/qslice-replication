"""srcML of the ansatz's loop nest with lettered highlights, and the iterations the tool keeps for q0.

Left: srcML's own text for lines 10-15 of programs/ansatz.py (srcML keeps the source's newlines and indentation).
Long rows are wrapped for display, and the two angle arguments are elided as an ellipsis; joining the rows must
give srcML's text back with only those two arguments replaced. Highlights: e <for> (unrolled), f the range
arguments (iteration counts, computed from lines 4-5), b the gate names, c the qubit arguments (resolved per
iteration). Right: for every gate line, a layer x qubit grid of its unrolled operations, filled where the
operation is in the wire-rule slice of q0. Everything comes from srcML and the tool (tool/interp.py,
tool/slicer.py); asserts the slice size reported in the paper (numAnsWireOps, from fig_programs_facts.json).
Usage (from the workspace root): python paper/figures/src/make_fig_srcml_loops.py
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent
ROOT = SRC.parents[2]
sys.path.insert(0, str(ROOT))
from tool.interp import trace_file  # noqa: E402
from tool.slicer import terminal, wire_slice  # noqa: E402

PROG = SRC / "programs" / "ansatz.py"
WRAP = 116  # display columns before a row is wrapped

HEAD = r"""% Generated by make_fig_srcml_loops.py from programs/ansatz.py, srcML and the tool. Do not edit by hand.
\documentclass[tikz,border=2pt]{standalone}
\usepackage[T1]{fontenc}
\usepackage{newtxtext,newtxmath}
\usepackage[varqu,scaled=0.95]{zi4}
\usetikzlibrary{arrows.meta,calc}
\definecolor{ink}{HTML}{1F2328}\definecolor{mute}{HTML}{6E7781}\definecolor{rule}{HTML}{D0D7DE}
\definecolor{wire}{HTML}{0969DA}\definecolor{wireL}{HTML}{DDEBFF}\definecolor{tree}{HTML}{8250DF}
\definecolor{hlC}{HTML}{FFF1B8}
\newcommand{\hlbox}[1]{{\setlength{\fboxsep}{0.4pt}\colorbox{hlC}{\strut #1}}}
\newcommand{\hlm}[1]{\raisebox{0.9ex}{\textcolor{tree}{\fontsize{4.4}{5}\selectfont\bfseries\rmfamily #1}}}
\newcommand{\hl}[1]{\textcolor{tree}{\bfseries #1}}
\tikzset{
  stage/.style={font=\footnotesize\bfseries, text=ink, anchor=west, inner sep=0pt},
  stnum/.style={circle, draw=ink, line width=0.6pt, font=\scriptsize\bfseries, text=ink, inner sep=0pt, minimum size=9pt},
  xml/.style={font=\ttfamily\fontsize{5.3}{6}\selectfont, anchor=west, inner sep=0pt},
  note/.style={font=\fontsize{6.2}{7.4}\selectfont\itshape, execute at begin node={\hyphenpenalty=10000}, text=mute, inner sep=0pt},
}
\begin{document}
\begin{tikzpicture}
"""


def tex(s: str) -> str:
    return (s.replace("\\", r"\textbackslash{}").replace("_", r"\_").replace("{", r"\{").replace("}", r"\}")
            .replace("#", r"\#").replace("%", r"\%").replace("&", r"\&").replace("~", r"\textasciitilde{}"))


ANGLE = re.compile(r"<argument><expr><call><name>float</name>.*?</call></expr></argument>(?=, <argument>)", re.S)


def fragment() -> str:
    xml = subprocess.run(["srcml", "-l", "Python", str(PROG)], capture_output=True, text=True, check=True).stdout
    i = xml.index("<for>")
    j = xml.rindex("</for>") + len("</for>")
    return xml[i:j]


def marked_tokens(shown: str):
    """(token, mark) over the whole text. Marks: e <for>; b gate name; f source text of a range argument;
    c source text of a gate's qubit argument (the angle argument, elided, is not marked). Only the first token of
    a marked span carries the letter."""
    toks = re.findall(r"<[^>]+>|[^<]+", shown)
    out, mode, depth = [], None, 0
    for i, t in enumerate(toks):
        m = None
        if t == "<for>":
            m = "e"
        elif t in ("ry", "rz", "cx") and toks[i - 1] == "<name>":
            m, mode = "b", "gate"
        elif t == "range" and toks[i - 1] == "<name>":
            mode = "range"
        elif not t.startswith("<"):
            if mode in ("range", "gate") and t.strip("(), ") and t != "…":
                m = "f" if mode == "range" else "c"
            if mode in ("range", "gate") and t.startswith(")"):
                mode = None
        out.append((t, m))
    return out


def render(row_tokens) -> str:
    out, prev = [], None
    for t, m in row_tokens:
        if t.startswith("<"):
            body = r"\textcolor{tree}{" + tex(t) + "}"
        elif t == "…":
            body = r"\textcolor{mute}{\rmfamily\itshape angle\,\ldots}"
        else:
            body = r"\textcolor{ink}{\bfseries " + tex(t) + "}"
        if m:
            body = r"\hlbox{" + body + "}"
            if m != prev:
                body += r"\hlm{" + m + "}"
        out.append(body)
        prev = m if m else (prev if (t.startswith("<") or not t.strip()) and prev in ("f", "c") else None)
    return "".join(out)


def main():
    frag = fragment()
    shown = ANGLE.sub("<argument>…</argument>", frag)
    assert shown.count("…") == 2, "expected the two angle arguments"
    # rows: srcML's own newlines; long rows wrapped at tag boundaries (display only)
    toks = []
    for t, m in marked_tokens(shown):
        parts = t.split("\n")
        for k, part in enumerate(parts):
            if k:
                toks.append(("\n", None))
            if part:
                toks.append((part, m))
    rows, cur, indent, first = [], [], 0, True
    def width(ts):
        return sum(len(t) for t, _ in ts)
    for t, m in toks:
        if t == "\n":
            rows.append((indent, cur, first))
            cur, first, indent = [], True, 0
            continue
        if not cur and first and not t.startswith("<") and t.strip() == "":
            indent = len(t)
            continue
        if not cur and first and not t.startswith("<") and t != t.lstrip(" "):
            indent = len(t) - len(t.lstrip(" "))
            t = t.lstrip(" ")
        if cur and width(cur) + len(t) > WRAP - indent:
            rows.append((indent, cur, first))
            cur, first = [], False
        cur.append((t, m))
    rows.append((indent, cur, first))
    rebuilt = "\n".join(" " * ind + "".join(t for t, _ in ts) if fs else "\x00" + "".join(t for t, _ in ts)
                        for ind, ts, fs in rows).replace("\n\x00", "")
    assert rebuilt == shown, "display rows do not reproduce srcML"

    # tool: unrolled operations and the slice of q0
    circ = trace_file(PROG).main_circuit()
    sl = wire_slice(circ, [0])
    facts = json.load(open(SRC / "fig_programs_facts.json"))["ansatz"]
    assert len(sl.ops) == len(facts["slices"]["lc"]), (len(sl.ops), len(facts["slices"]["lc"]))
    term = terminal(circ)
    keep = set(sl.ops)

    o = [HEAD]
    WL, GAP, WR = 11.3, 0.4, 6.0
    o.append(r"\node[stnum] at (0.16,0.5) {1};")
    o.append(r"\node[stage] at (0.38,0.5) {srcML of the loop nest (lines 10--15)};")
    o.append(rf"\draw[rule, line width=0.6pt] (0,0.28) -- ({WL},0.28);")
    pitch = 0.235
    for i, (ind, ts, first) in enumerate(rows):
        x = 0.05 + (0.088 * ind if first else 0.088 * (ind + 4))
        lead = "" if first else r"\textcolor{mute}{\rmfamily\fontsize{5}{6}\selectfont$\hookrightarrow$}\,"
        o.append(rf"\node[xml] at ({x},{-i * pitch}) {{{lead}{render(ts)}}};")
    ybot = -len(rows) * pitch
    legend = (r"\hl{e}\,\texttt{for} $\to$ unrolled, iteration numbers kept\quad "
              r"\hl{f}\,range $\to$ iteration count, from lines 4--5 ($n{=}3$, $\mathit{layers}{=}2$)\\"
              r"\hl{b}\,gate name\quad \hl{c}\,\texttt{qubit}, \texttt{qubit + 1} $\to$ a qubit per iteration\quad "
              r"\textcolor{mute}{\itshape angle\,\ldots}: argument elided; the tool keeps it symbolic")
    o.append(rf"\node[anchor=north west, align=left, font=\fontsize{{6.2}}{{7.6}}\selectfont, text=ink, inner sep=0pt] at (0.05,{ybot + 0.02}) {{{legend}}};")

    # right: iteration grids
    X = WL + GAP
    o.append(rf"\node[stnum] at ({X + 0.16},0.5) {{2}};")
    o.append(rf"\node[stage] at ({X + 0.38},0.5) {{Unrolled operations in the slice of $q_0$}};")
    o.append(rf"\draw[rule, line width=0.6pt] ({X},0.28) -- ({X + WR},0.28);")
    cell = 0.3
    gx = X + 0.75
    for gi, (line, name) in enumerate(((12, "ry"), (13, "rz"), (15, "cx"))):
        ops = [(k, op) for k, op in enumerate(circ.ops) if op.line == line and k not in term]
        layers = sorted({op.iters[0][1] for _, op in ops})
        cols = sorted({tuple(sorted(next(iter(s)) for s in op.qubits)) for _, op in ops})
        x0 = gx + gi * 1.8
        n_in = sum(k in keep for k, _ in ops)
        o.append(rf"\node[font=\fontsize{{6.3}}{{7.4}}\selectfont, text=ink, anchor=south, align=center] at ({x0 + len(cols) * cell / 2},{-0.42}) "
                 rf"{{line {line}, \texttt{{{name}}}\\[-1pt]\textcolor{{wire}}{{\bfseries {n_in}}} of {len(ops)}}};")
        for li, layer in enumerate(layers):
            y = -0.72 - li * cell
            if gi == 0:
                o.append(rf"\node[font=\fontsize{{5.8}}{{6.5}}\selectfont, text=mute, anchor=east] at ({x0 - 0.06},{y - cell / 2}) {{layer {layer}}};")
            for ci, qs in enumerate(cols):
                k = next(k for k, op in ops if op.iters[0][1] == layer and tuple(sorted(next(iter(s)) for s in op.qubits)) == qs)
                fill = "wire" if k in keep else "white"
                o.append(rf"\draw[draw=ink!45, line width=0.4pt, fill={fill}] ({x0 + ci * cell},{y}) rectangle ++({cell - 0.04},{-(cell - 0.04)});")
        for ci, qs in enumerate(cols):
            lab = (r"$q_{%d%d}$" % qs) if len(qs) > 1 else (r"$q_{%d}$" % qs[0])
            o.append(rf"\node[font=\fontsize{{5.6}}{{6}}\selectfont, text=mute, anchor=north] at ({x0 + ci * cell + (cell - 0.04) / 2},{-0.72 - len(layers) * cell - 0.02}) {{{lab}}};")
    tot = len(keep)
    allops = len(circ.ops) - len(term)
    o.append(rf"\node[note, anchor=north west, align=left, text width={WR - 0.1}cm] at ({X + 0.05},{-1.85}) "
             rf"{{Filled: in the wire-rule slice of $q_0$ ({tot} of {allops} operations). The lines are the same in every "
             r"iteration, but in the second layer the rotations of $q_2$ and its \texttt{cx} are not dependences of $q_0$; "
             r"a line-level slice keeps lines 12, 13 and 15 anyway.};")
    o.append(r"\end{tikzpicture}")
    o.append(r"\end{document}")
    (SRC / "fig_srcml_loops.tex").write_text("\n".join(o) + "\n")
    print("wrote fig_srcml_loops.tex | rows", len(rows), "| slice", tot, "of", allops)


if __name__ == "__main__":
    main()
