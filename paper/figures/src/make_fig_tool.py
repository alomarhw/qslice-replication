"""The tool on the ansatz of Fig. 2: srcML, the operation trace it yields, and the slice of q0 by line and iteration.

(1) srcML's own text for two parts of programs/ansatz.py, the CNOT loop (lines 14-15) and the mid-circuit
measurement with the conditioned flip (lines 18-20), from srcml --position. Only the first tag of each part keeps
its position, the two line comments are elided, and long rows are wrapped for display; joining the rows must give
that text back. Lettered highlights mark what the tool reads: a <for> (unrolled), b the range argument (the
iteration count), c gate names, d qubit arguments (evaluated per iteration), e bit arguments and the condition,
f the <with> of if_test (the conditioned block), g the position (the source line).
(2) The tool's trace of the program, one row per operation, with its line and loop iteration; the rotations of
lines 12 and 13 are summarised in one row.
(3) For every gate line, the unrolled operations, filled where they are in the QDG slice of q0.
Everything comes from srcML and the tool (tool/interp.py, tool/slicer.py). Asserts that the trace has the
operations of Fig. 2 (fig_programs_facts.json, the study's circuit) in order and that the slice has its size.
Usage (from the workspace root): python paper/figures/src/make_fig_tool.py
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent
ROOT = SRC.parents[2]
sys.path.insert(0, str(ROOT))
from tool.interp import trace_file  # noqa: E402
from tool.slicer import terminal, wire_slice  # noqa: E402

PROG = SRC / "programs" / "ansatz.py"
WRAP = 154  # display columns before a row is wrapped
CH = 0.1091  # width of one srcML character (cm)
GATES = ("cx", "measure", "x")

HEAD = r"""% Generated by make_fig_tool.py from programs/ansatz.py, srcML and the tool. Do not edit by hand.
\documentclass[tikz,border=2pt]{standalone}
\usepackage[T1]{fontenc}
\usepackage{newtxtext,newtxmath}
\usepackage[varqu,scaled=0.95]{zi4}
\usetikzlibrary{arrows.meta,calc}
\definecolor{ink}{HTML}{1F2328}\definecolor{mute}{HTML}{6E7781}\definecolor{rule}{HTML}{D0D7DE}
\definecolor{wire}{HTML}{0969DA}\definecolor{wireL}{HTML}{DDEBFF}\definecolor{tree}{HTML}{6639BA}
\definecolor{hlC}{HTML}{FFF1B8}
\newcommand{\hlbox}[1]{{\setlength{\fboxsep}{0.4pt}\colorbox{hlC}{\strut #1}}}
\newcommand{\hlm}[1]{\raisebox{0.9ex}{\textcolor{tree}{\fontsize{6.3}{7}\selectfont\bfseries\rmfamily #1}}}
\newcommand{\hl}[1]{\textcolor{tree}{\bfseries #1}}
\tikzset{
  >={Stealth[length=3.6pt,width=3.2pt]},
  stage/.style={font=\footnotesize\bfseries, text=ink, anchor=west, inner sep=0pt},
  stnum/.style={circle, draw=ink, line width=0.6pt, font=\scriptsize\bfseries, text=ink, inner sep=0pt, minimum size=9pt},
  xml/.style={font=\ttfamily\fontsize{6.5}{7.3}\selectfont, anchor=west, inner sep=0pt},
  note/.style={font=\fontsize{7.2}{8.6}\selectfont\itshape, execute at begin node={\hyphenpenalty=10000}, text=mute, inner sep=0pt},
  flowarrow/.style={->, line width=0.7pt, draw=ink},
}
\begin{document}
\begin{tikzpicture}
"""


def tex(s: str) -> str:
    return (s.replace("\\", r"\textbackslash{}").replace("_", r"\_").replace("{", r"\{").replace("}", r"\}")
            .replace("#", r"\#").replace("%", r"\%").replace("&", r"\&").replace("~", r"\textasciitilde{}"))


COMMENT = re.compile(r"\s*<comment type=\"line\"[^>]*>[^<]*</comment>")
POS = re.compile(r' pos:(?:start|end)="[^"]*"')


def fragments():
    """The two parts of the program as srcML text, each keeping the position of its first tag only."""
    xml = subprocess.run(["srcml", "--position", "-l", "Python", str(PROG)], capture_output=True, text=True,
                         check=True).stdout
    loop = re.search(r'<for pos:start="14:\d+"[^>]*>.*?</for>', xml, re.S).group(0)
    cond = re.search(r'<expr_stmt pos:start="18:\d+"[^>]*>.*?</with>', xml, re.S).group(0)
    out = []
    for frag in (loop, cond):
        head, rest = frag.split(">", 1)
        head = re.sub(r' pos:end="[^"]*"', "", head)
        out.append(head + ">" + POS.sub("", rest))
    return out


def marked_tokens(shown: str):
    """(token, mark) over a fragment; marks as in the module docstring."""
    toks = re.findall(r"<[^>]+>|[^<]+", shown)
    out, lists, depth, in_index = [], [], 0, 0
    callee = None
    for i, t in enumerate(toks):
        m = None
        if t.startswith("<"):
            if t.startswith("<for"):
                m = "a"
            elif t.startswith("<with"):
                m = "f"
            if "pos:start" in t:
                m = "g"
            if t == "<argument_list>":
                lists.append({"callee": callee, "arg": -1, "depth": depth})
            elif t == "</argument_list>":
                lists.pop()
            elif t == "<argument>":
                depth += 1
                if lists and depth == lists[-1]["depth"] + 1:
                    lists[-1]["arg"] += 1
            elif t == "</argument>":
                depth -= 1
            elif t == "<index>":
                in_index += 1
            elif t == "</index>":
                in_index -= 1
        else:
            word = t.strip("(),:[] ")
            if word and toks[i - 1] == "<name>" and i + 1 < len(toks) and toks[i + 1] == "</name>":
                callee = word
            if word and not t.isspace():
                nxt = toks[i + 1:i + 4]
                if word == "for" and toks[i - 1].startswith("<for"):
                    m = "a"  # the <for> tag carries the position (g), so the keyword carries a
                elif word in GATES + ("if_test",) and nxt[:2] == ["</name>", "</name>"] and nxt[2] == "<argument_list>":
                    m = "c" if word in GATES else "f"
                elif lists:
                    top = lists[-1]
                    if top["callee"] == "range":
                        m = "b"
                    elif top["callee"] == "if_test":
                        m = "e" if word == "clbits" or in_index else None  # the bit, not qc or the value
                    elif top["callee"] == "measure":
                        m = "d" if top["arg"] == 0 else "e"
                    elif top["callee"] in GATES:
                        m = "d"
                if in_index and m:
                    m = "e"
        out.append((t, m))
    return out


def render(row_tokens, state) -> str:
    """A display row; the letter of a mark is printed on the first token of each run of that mark."""
    out = []
    for t, m in row_tokens:
        if t.startswith("<"):
            if m == "g":
                p = re.search(r'pos:start="[^"]*"', t).group(0)
                body = r"\textcolor{tree}{" + tex(t).replace(tex(p), r"\hlbox{" + tex(p) + "}") + "}"
            else:
                body = r"\textcolor{tree}{" + tex(t) + "}"
        else:
            body = r"\textcolor{ink}{\bfseries " + tex(t) + "}"
        if m:
            body = r"\hlbox{" + body + "}" if m != "g" else body
            if m != state["last"]:
                body += r"\hlm{" + m + "}"
            state["last"] = m
        elif not t.startswith("<") and re.search(r"\w", t):
            state["last"] = None
        out.append(body)
    return "".join(out)


def rows_of(shown: str):
    """Display rows (indent, tokens, first-of-source-line) whose join gives `shown` back."""
    toks = []
    for t, m in marked_tokens(shown):
        for k, part in enumerate(t.split("\n")):
            if k:
                toks.append(("\n", None))
            if part:
                toks.append((part, m))
    rows, cur, indent, first = [], [], 0, True

    def width(ts):
        return sum(len(t) for t, _ in ts)
    for t, m in toks:
        if t == "\n":
            rows.append((indent, cur, first))
            cur, first, indent = [], True, 0
            continue
        if not cur and first and not t.startswith("<") and t.strip() == "":
            indent = len(t)
            continue
        if not cur and first and not t.startswith("<") and t != t.lstrip(" "):
            indent = len(t) - len(t.lstrip(" "))
            t = t.lstrip(" ")
        if cur and width(cur) + len(t) > WRAP - indent:
            rows.append((indent, cur, first))
            cur, first = [], False
        cur.append((t, m))
    rows.append((indent, cur, first))
    rebuilt = "\n".join(" " * ind + "".join(t for t, _ in ts) if fs else "\x00" + "".join(t for t, _ in ts)
                        for ind, ts, fs in rows).replace("\n\x00", "")
    assert rebuilt == shown, "display rows do not reproduce srcML"
    return rows


def q(op, k=0):
    return next(iter(op.qubits[k]))


def main():
    frags = fragments()
    shown = []
    for f in frags:
        s, n = COMMENT.subn("", f)
        shown.append(s)
    assert [COMMENT.subn("", f)[1] for f in frags] == [0, 2], "expected the two line comments of lines 18 and 20"

    # tool: the trace and the slice of q0
    circ = trace_file(PROG).main_circuit()
    term = terminal(circ)
    ops = [(k, op) for k, op in enumerate(circ.ops) if k not in term]
    sl = wire_slice(circ, [0])
    keep = set(sl.ops)
    facts = json.load(open(SRC / "fig_programs_facts.json"))["ansatz"]
    fops = [(o["name"], o["qubits"], o["line"]) for o in facts["ops"]]
    # the study's circuit holds the conditioned x as an if_else on the with-line, the tool as x with a condition
    tops = [("if_else", [q(op)], op.line - 1) if op.cond else (op.name, [q(op, j) for j in range(len(op.qubits))], op.line)
            for _, op in ops]
    assert tops == fops, "tool trace != the study's circuit of Fig. 2"
    assert sorted(i for i, (k, _) in enumerate(ops) if k in keep) == facts["slices"]["lc"], "tool slice != study slice"

    o = [HEAD]
    # stage 1 spans the width; stages 2 and 3 sit side by side under it
    WL, WT, WR, GAP = 17.7, 7.0, 10.3, 0.4
    XT = 0.0
    XR = XT + WT + GAP

    def header(x, n, title, w):
        o.append(rf"\node[stnum] at ({x + 0.16},0.5) {{{n}}};")
        o.append(rf"\node[stage] at ({x + 0.38},0.5) {{{title}}};")
        o.append(rf"\draw[rule, line width=0.6pt] ({x},0.28) -- ({x + w},0.28);")

    # ---- 1 srcML
    header(0, 1, "srcML of lines 14--15 and 18--20", WL)
    pitch, y, state = 0.28, 0.0, {"last": None}
    for fi, s in enumerate(shown):
        if fi:
            y -= 0.15
            state["last"] = None
        for ind, ts, first in rows_of(s):
            x = 0.05 + (CH * ind if first else CH * (ind + 4))
            lead = "" if first else r"\textcolor{mute}{\rmfamily\fontsize{6.6}{7}\selectfont$\hookrightarrow$}\,"
            o.append(rf"\node[xml] at ({x},{y}) {{{lead}{render(ts, state)}}};")
            y -= pitch
    legend = (r"\hl{a}\,\texttt{for} $\to$ unrolled\enspace "
              r"\hl{b}\,range $\to$ iteration count, from line 4\enspace "
              r"\hl{c}\,gate\enspace \hl{d}\,qubit argument, evaluated per iteration\\"
              r"\hl{e}\,classical bit, written by the measurement and read by the condition\enspace "
              r"\hl{f}\,\texttt{if\_test} $\to$ conditioned block\enspace \hl{g}\,position $\to$ source line")
    o.append(rf"\node[anchor=north west, align=left, font=\fontsize{{7.2}}{{8.6}}\selectfont, text=ink, inner sep=0pt] "
             rf"at (0.05,{y + 0.08}) {{{legend}}};")
    ybot = y - 1.05
    o.append(rf"\begin{{scope}}[yshift={ybot - 0.5:.3f}cm]")

    # ---- 2 trace
    header(XT, 2, "Trace", WT)
    rot = [(k, op) for k, op in ops if op.line in (12, 13)]
    assert {op.name for _, op in rot} == {"ry", "rz"}
    trow = [r"\textcolor{mute}{line}&\textcolor{mute}{iteration}&\textcolor{mute}{operation}\\[1pt]",
            rf"12, 13&\textcolor{{mute}}{{every}}&{len(rot)} rotations\\[1pt]"]
    for k, op in ops:
        if op.line in (12, 13):
            continue
        it = ", ".join(str(v) for _, v in op.iters) if op.iters else r"\textcolor{mute}{--}"
        qs = r",\,".join("$q_%d$" % q(op, j) for j in range(len(op.qubits)))
        txt = rf"\texttt{{{op.name}}} {qs}"
        if op.clbits:
            txt += r" $\to$ $c_{%d}$" % next(iter(op.clbits[0]))
        if op.cond:
            txt += r" if $c_{%d}$" % next(iter(op.cond))
        trow.append(rf"{op.line}&{it}&{txt}\\[1pt]")
    o.append(rf"\node[anchor=north west, font=\fontsize{{7.6}}{{9.4}}\selectfont, text=ink, inner sep=0pt] (trace) at ({XT + 0.04},{-0.05}) "
             rf"{{\setlength{{\tabcolsep}}{{5pt}}\begin{{tabular}}{{rll}}{''.join(trow)}\end{{tabular}}}};")
    o.append(rf"\node[note, anchor=north west, align=left, text width={WT - 0.1}cm] at ($(trace.south west)+(0,-0.12)$) "
             r"{An iteration lists the values of \texttt{layer} and \texttt{qubit}. The measurements of line 21 are "
             r"terminal and not shown.};")

    # ---- 3 slice by line and iteration
    header(XR, 3, "Slice of $q_0$", WR)
    cell = 0.42
    gx = XR + 1.0
    GS = 2.35  # spacing of the line groups
    for gi, (line, name) in enumerate(((12, "ry"), (13, "rz"), (15, "cx"))):
        lops = [(k, op) for k, op in ops if op.line == line]
        layers = sorted({op.iters[0][1] for _, op in lops})
        cols = sorted({tuple(q(op, j) for j in range(len(op.qubits))) for _, op in lops})
        x0 = gx + gi * GS
        n_in = sum(k in keep for k, _ in lops)
        o.append(rf"\node[font=\fontsize{{7.4}}{{8.6}}\selectfont, text=ink, anchor=south, align=center] at "
                 rf"({x0 + len(cols) * cell / 2},{-0.5}) {{line {line}, \texttt{{{name}}}\\[-1pt]"
                 rf"\textcolor{{wire}}{{\bfseries {n_in}}} of {len(lops)}}};")
        for li, layer in enumerate(layers):
            yy = -0.8 - li * cell
            if gi == 0:
                o.append(rf"\node[font=\fontsize{{7}}{{8}}\selectfont, text=mute, anchor=east] at ({x0 - 0.05},{yy - cell / 2}) {{layer {layer}}};")
            for ci, qs in enumerate(cols):
                k = next(k for k, op in lops if op.iters[0][1] == layer and tuple(q(op, j) for j in range(len(op.qubits))) == qs)
                fill = "wire" if k in keep else "white"
                o.append(rf"\draw[draw=ink!45, line width=0.4pt, fill={fill}] ({x0 + ci * cell},{yy}) rectangle ++({cell - 0.04},{-(cell - 0.04)});")
        for ci, qs in enumerate(cols):
            lab = (r"$q_{%d%d}$" % qs) if len(qs) > 1 else (r"$q_{%d}$" % qs[0])
            o.append(rf"\node[font=\fontsize{{6.8}}{{7.4}}\selectfont, text=mute, anchor=north] at "
                     rf"({x0 + ci * cell + (cell - 0.04) / 2},{-0.8 - len(layers) * cell - 0.02}) {{{lab}}};")
    # the dynamic step: one operation per line
    dyn = [(k, op) for k, op in ops if op.line in (17, 18, 20)]
    yd = -2.15
    o.append(rf"\node[font=\fontsize{{7.4}}{{8.6}}\selectfont, text=ink, anchor=west] at ({XR + 0.05},{yd - cell / 2 + 0.02}) "
             rf"{{lines 17, 18, 20\enspace\textcolor{{wire}}{{\bfseries {sum(k in keep for k, _ in dyn)}}} of {len(dyn)}}};")
    for ci, (k, op) in enumerate(dyn):
        o.append(rf"\draw[draw=ink!45, line width=0.4pt, fill={'wire' if k in keep else 'white'}] "
                 rf"({XR + 2.75 + ci * cell},{yd}) rectangle ++({cell - 0.04},{-(cell - 0.04)});")
    tot, allops = len(keep & {k for k, _ in ops}), len(ops)
    assert tot == len(facts["slices"]["lc"]) and allops == len(facts["ops"]), (tot, allops)
    o.append(rf"\node[note, anchor=north west, align=left, text width={WR - 0.1}cm] at ({XR + 0.05},{yd - 0.6}) "
             rf"{{Filled squares are in the QDG slice of $q_0$, {tot} of {allops} operations. Every iteration runs the "
             r"same lines, but in the second layer the rotations of $q_2$ and its \texttt{cx} are not dependences of "
             r"$q_0$, and a slice of lines keeps lines 12, 13 and 15 anyway.};")

    o.append(rf"\draw[flowarrow] ({XT + WT + 0.04},0.28) -- ({XR - 0.04},0.28);")
    o.append(r"\end{scope}")
    o.append(r"\end{tikzpicture}")
    o.append(r"\end{document}")
    (SRC / "fig_tool.tex").write_text("\n".join(o) + "\n")
    print("wrote fig_tool.tex | slice", tot, "of", allops, "| lines", sorted(sl.quantum_lines), sorted(sl.classical_lines))


if __name__ == "__main__":
    main()
