import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent
ROOT = SRC.parents[2]
sys.path.insert(0, str(ROOT))
from tool.interp import trace_file  # noqa: E402
from tool.slicer import terminal, wire_slice  # noqa: E402

BUG = "stackoverflow-6-10/bug_2/buggy.py"
FAULT = 6        # circuit.h(1) should be circuit.x(1) (Bugs4Q fixed.py)
SHOW = range(4, 9)

HEAD = r"""% Generated by make_fig_overview.py from the Bugs4Q original and the tool's output. Do not edit by hand.
\documentclass[tikz,border=2pt]{standalone}
\usepackage[T1]{fontenc}
\usepackage{newtxtext,newtxmath}
\usepackage[varqu,scaled=0.95]{zi4}
\usetikzlibrary{arrows.meta,positioning,calc,backgrounds,fit}
\definecolor{ink}{HTML}{1F2328}\definecolor{mute}{HTML}{6E7781}\definecolor{rule}{HTML}{D0D7DE}
\definecolor{wire}{HTML}{0969DA}\definecolor{wireL}{HTML}{DDEBFF}
\definecolor{fault}{HTML}{CF4A1B}\definecolor{faultL}{HTML}{FCE4DA}
\definecolor{pdg}{HTML}{8C959F}\definecolor{tree}{HTML}{8250DF}\definecolor{treeL}{HTML}{F1EAFE}
\tikzset{
  >={Stealth[length=3.6pt,width=3.2pt]},
  stage/.style={font=\footnotesize\bfseries, text=ink, anchor=south west, inner sep=0pt},
  stnum/.style={circle, draw=ink, line width=0.6pt, font=\scriptsize\bfseries, text=ink, inner sep=0pt, minimum size=9pt},
  code/.style={font=\ttfamily\fontsize{6.3}{8}\selectfont, text=ink, anchor=west, inner sep=0pt},
  lno/.style={font=\ttfamily\fontsize{6.3}{8}\selectfont, text=mute, anchor=east, inner sep=0pt},
  xn/.style={rectangle, rounded corners=1.6pt, draw=tree, fill=treeL, line width=0.5pt,
        font=\ttfamily\fontsize{6}{7}\selectfont, text=ink, inner xsep=2.2pt, inner ysep=1.6pt},
  xleaf/.style={font=\ttfamily\fontsize{6}{7}\selectfont, text=ink, inner sep=1pt},
  gate/.style={rectangle, draw=ink, fill=white, line width=0.55pt, minimum size=11pt, inner sep=0pt,
        font=\fontsize{7}{8}\selectfont},
  note/.style={font=\fontsize{6.4}{7.6}\selectfont\itshape, execute at begin node={\hyphenpenalty=10000\exhyphenpenalty=10000}, text=mute, align=center, inner sep=1pt},
  flowarrow/.style={->, line width=0.7pt, draw=ink},
}
\begin{document}
\begin{tikzpicture}
"""


def tex(s: str) -> str:
    return (s.replace("\\", r"\textbackslash{}").replace("_", r"\_").replace("{", r"\{").replace("}", r"\}")
            .replace("#", r"\#").replace("%", r"\%").replace("&", r"\&").replace("~", r"\textasciitilde{}"))


def srcml_stmt(path: Path, line: int):
    """srcML element names under the expression statement on `line` (real output of srcML --position)."""
    xml = subprocess.run(["srcml", "--position", "-l", "Python", str(path)], capture_output=True, text=True, check=True).stdout
    m = re.search(r'<expr_stmt pos:start="(%d:\d+)"' % line, xml)
    assert m, "no srcML expr_stmt on that line"
    body = xml[m.start(): xml.index("</expr_stmt>", m.start())]
    names = re.findall(r"<(\w+)[ >]", body)
    for need in ("expr_stmt", "call", "name", "argument_list", "argument", "literal"):
        assert need in names, need
    lits = re.findall(r'<literal type="number"[^>]*>([^<]+)</literal>', body)
    callee = "".join(re.findall(r"<name[^>]*>(\w+)</name>", body.split("<argument_list")[0]))
    return m.group(1), callee, lits


def main():
    path = Path(sys.argv[1]) / BUG
    src = path.read_text().splitlines()
    circ = trace_file(path).main_circuit()
    wire = wire_slice(circ, [0])
    pdg = wire_slice(circ, [0], rule="cpdg")
    assert sorted(wire.quantum_lines) == [5, 6, 7] and sorted(wire.classical_lines) == [4], wire
    assert sorted(pdg.quantum_lines) == [5], pdg
    term = terminal(circ)
    ops = [o for k, o in enumerate(circ.ops) if k not in term]
    cx = next(o for o in ops if o.name == "cx")
    pos, callee, lits = srcml_stmt(path, cx.line)
    assert callee.endswith("cx") and lits == ["0", "1"], (callee, lits)

    o = [HEAD]
    dy = 0.36                      # line pitch (cm)
    top = 0.0
    W1, W2, W3, W4, GAP = 3.45, 3.95, 3.85, 3.95, 0.86
    X1 = 0.0
    X2 = X1 + W1 + GAP
    X3 = X2 + W2 + GAP
    X4 = X3 + W3 + GAP

    def header(x, n, title, w):
        o.append(rf"\node[stnum] (n{n}) at ({x + 0.16},{top + 0.55}) {{{n}}};")
        o.append(rf"\node[stage, anchor=west] at ({x + 0.38},{top + 0.55}) {{{title}}};")
        o.append(rf"\draw[rule, line width=0.6pt] ({x},{top + 0.3}) -- ({x + w},{top + 0.3});")

    # ---------------------------------------------------------------- 1 source
    header(X1, 1, "Qiskit program", W1)
    for i, n in enumerate(SHOW):
        y = top - i * dy
        if n == FAULT:
            o.append(rf"\fill[faultL, rounded corners=1pt] ({X1 + 0.02},{y - 0.15}) rectangle ({X1 + W1 - 0.02},{y + 0.17});")
        o.append(rf"\node[lno] at ({X1 + 0.32},{y}) {{{n}}};")
        o.append(rf"\node[code] at ({X1 + 0.42},{y}) {{{tex(src[n - 1].strip())}}};")
    yf = top - (FAULT - SHOW.start) * dy
    o.append(rf"\node[font=\fontsize{{6.2}}{{7}}\selectfont\bfseries, text=fault, anchor=east] at ({X1 + W1 - 0.06},{yf}) {{fault}};")
    yb = top - len(SHOW) * dy
    o.append(rf"\node[code, text=mute] at ({X1 + 0.42},{yb}) {{\itshape\rmfamily\fontsize{{6.3}}{{8}}\selectfont lines 10--16: run on a simulator, print}};")
    o.append(rf"\node[note, anchor=north west, align=left, text width={W1 - 0.1}cm] at ({X1 + 0.05},{yb - 0.3}) "
             r"{Expected $(\lvert01\rangle{+}\lvert10\rangle)/\sqrt{2}$; line~6 should apply $X$.}")
    o[-1] += ";"

    # ---------------------------------------------------------------- 2 srcML tree
    header(X2, 2, "srcML, line 7", W2)
    bx = X2 + 0.15
    o.append(rf"\node[xn, anchor=north west] (es) at ({bx},{top + 0.12}) {{expr\_stmt\ \textcolor{{mute}}{{pos=\textquotedbl{pos}\textquotedbl}}}};")
    o.append(rf"\node[xn, anchor=north west] (cl) at ({bx + 0.35},{top - 0.42}) {{call}};")
    o.append(rf"\node[xn, anchor=north west] (nm) at ({bx + 0.7},{top - 0.96}) {{name}};")
    o.append(rf"\node[xleaf, anchor=west] at ($(nm.east)+(0.08,0)$) {{{tex(callee.replace('cx', '.cx') if '.' not in callee else callee)}}};")
    o.append(rf"\node[xn, anchor=north west] (al) at ({bx + 0.7},{top - 1.5}) {{argument\_list}};")
    o.append(rf"\node[xn, anchor=north west] (a0) at ({bx + 1.05},{top - 2.04}) {{argument}};")
    o.append(rf"\node[xleaf, anchor=west] at ($(a0.east)+(0.08,0)$) {{{lits[0]}}};")
    o.append(rf"\node[xn, anchor=north west] (a1) at ({bx + 1.05},{top - 2.58}) {{argument}};")
    o.append(rf"\node[xleaf, anchor=west] at ($(a1.east)+(0.08,0)$) {{{lits[1]}}};")
    for p, c in (("es", "cl"), ("cl", "nm"), ("cl", "al"), ("al", "a0"), ("al", "a1")):
        o.append(rf"\draw[tree, line width=0.5pt] ($({p}.south west)+(0.17,0)$) |- ({c}.west);")
    # derived quantum fact, attached to <call>
    fact = (rf"\textbf{{cx}}: control $q_{{{lits[0]}}}$, target $q_{{{lits[1]}}}$\\"
            r"\textcolor{wire}{wire rule: writes both}")
    o.append(rf"\node[draw=wire, fill=white, rounded corners=1.6pt, line width=0.55pt, font=\fontsize{{6.3}}{{7.6}}\selectfont, "
             rf"text=ink, align=left, inner sep=2.2pt, anchor=north east] (fact) at ({X2 + W2 - 0.02},{top - 0.2}) {{{fact}}};")
    o.append(r"\draw[wire, line width=0.55pt, dash pattern=on 1.4pt off 1pt] (cl.east) -- (cl.east -| fact.west);")

    # ---------------------------------------------------------------- 3 trace as a circuit
    header(X3, 3, "Operation trace", W3)
    yq0, yq1 = top - 0.55, top - 1.45
    xs = {o_.line: X3 + 0.72 + 0.74 * i for i, o_ in enumerate(ops)}
    xe = X3 + 0.72 + 0.74 * len(ops) - 0.2
    for q, y in ((0, yq0), (1, yq1)):
        o.append(rf"\node[font=\fontsize{{7}}{{8}}\selectfont, text=ink, anchor=east] at ({X3 + 0.4},{y}) {{$q_{q}$}};")
        o.append(rf"\draw[ink, line width=0.5pt] ({X3 + 0.45},{y}) -- ({xe},{y});")
    for op in ops:
        x = xs[op.line]
        insl = op.line in wire.quantum_lines
        fillc = "faultL" if op.line == FAULT else ("wireL" if insl else "white")
        drawc = "fault" if op.line == FAULT else "ink"
        if op.name == "cx":
            c, t = (next(iter(s)) for s in op.qubits)
            yc, yt = (yq0 if c == 0 else yq1), (yq0 if t == 0 else yq1)
            o.append(rf"\fill[wireL, rounded corners=1.5pt] ({x - 0.2},{yt - 0.22}) rectangle ({x + 0.2},{yc + 0.22});")
            o.append(rf"\draw[ink, line width=0.55pt] ({x},{yc}) -- ({x},{yt - 0.12});")
            o.append(rf"\fill[ink] ({x},{yc}) circle (1.5pt);")
            o.append(rf"\draw[ink, line width=0.55pt, fill=white] ({x},{yt}) circle (3.3pt);")
            o.append(rf"\draw[ink, line width=0.55pt] ({x - 0.116},{yt}) -- ({x + 0.116},{yt}) ({x},{yt - 0.116}) -- ({x},{yt + 0.116});")
        else:
            y = yq0 if next(iter(op.qubits[0])) == 0 else yq1
            o.append(rf"\node[gate, fill={fillc}, draw={drawc}] at ({x},{y}) {{{op.name.upper()}}};")
        o.append(rf"\node[font=\fontsize{{6}}{{7}}\selectfont, text={'fault' if op.line == FAULT else 'mute'}] at ({x},{yq0 + 0.36}) {{line {op.line}}};")
    # criterion and kickback
    o.append(rf"\draw[wire, line width=0.8pt] ({xe + 0.02},{yq0 - 0.17}) -- ({xe + 0.02},{yq0 + 0.17});")
    o.append(rf"\node[font=\fontsize{{6.3}}{{7}}\selectfont, text=wire, anchor=west, align=left] at ({xe + 0.06},{yq0}) {{criterion\\[-1pt]$\{{q_0\}}$}};")
    xcx = xs[cx.line]
    o.append(rf"\draw[->, wire, line width=0.75pt] ({xcx - 0.05},{yq1 + 0.2}) to[bend left=40] ({xcx - 0.05},{yq0 - 0.13});")
    o.append(rf"\node[font=\fontsize{{6}}{{7}}\selectfont, text=wire, align=right, anchor=east] at ({xcx - 0.2},{(yq0 + yq1) / 2 + 0.02}) "
             r"{kickback:\\[-1pt]\texttt{cx} writes $q_0$};")
    o.append(rf"\node[note, anchor=north west, align=left, text width={W3 - 0.1}cm] at ({X3 + 0.05},{yq1 - 0.42}) "
             r"{shaded: kept by the wire rule's backward pass from $q_0$. The terminal measurement of line~8 is "
             r"outside the criterion.};")

    # ---------------------------------------------------------------- 4 slice on the source
    header(X4, 4, "Slice of $q_0$", W4)
    cw, cp = X4 + 0.2, X4 + 0.68
    o.append(rf"\node[font=\fontsize{{5.8}}{{6.5}}\selectfont\bfseries, text=wire] at ({cw},{top + 0.13}) {{wire}};")
    o.append(rf"\node[font=\fontsize{{5.8}}{{6.5}}\selectfont\bfseries, text=pdg] at ({cp},{top + 0.13}) {{PDG}};")
    for i, n in enumerate(SHOW):
        y = top - 0.12 - i * dy
        if n == FAULT:
            o.append(rf"\fill[faultL, rounded corners=1pt] ({X4 + 0.02},{y - 0.15}) rectangle ({X4 + W4 - 0.02},{y + 0.17});")
        inw, inp = n in wire.lines, n in pdg.lines
        if inw:
            col = "wire" if n in wire.quantum_lines else "wire!45"
            o.append(rf"\fill[{col}] ({cw - 0.09},{y - 0.1}) rectangle ({cw + 0.09},{y + 0.1});")
        if inp:
            col = "pdg" if n in pdg.quantum_lines else "pdg!50"
            o.append(rf"\fill[{col}] ({cp - 0.09},{y - 0.1}) rectangle ({cp + 0.09},{y + 0.1});")
        o.append(rf"\node[lno] at ({X4 + 1.17},{y}) {{{n}}};")
        o.append(rf"\node[code] at ({X4 + 1.25},{y}) {{{tex(src[n - 1].strip())}}};")
    yf = top - 0.12 - (FAULT - SHOW.start) * dy
    o.append(rf"\node[font=\fontsize{{6.2}}{{7}}\selectfont, text=fault, anchor=north west, align=left] at ({X4 + 0.02},{top - 0.12 - len(SHOW) * dy + 0.05}) "
             r"{\textbf{wire rule:} fault line~6 kept\\\textbf{classical PDG:} line~5 only, fault missed};")
    o.append(rf"\node[note, anchor=north west, align=left, text width={W4 - 0.1}cm] at ({X4 + 0.02},{top - 0.12 - len(SHOW) * dy - 0.55}) "
             r"{full square: quantum line; light: classical line (circuit construction).};")

    # ---------------------------------------------------------------- steps between stages
    for xa, xb, lab in ((X1 + W1, X2, "parse"), (X2 + W2, X3, "interpret"), (X3 + W3, X4, "slice")):
        ym = top + 0.3
        o.append(rf"\draw[flowarrow] ({xa + 0.06},{ym}) -- ({xb - 0.06},{ym});")
        o.append(rf"\node[note, anchor=south, font=\fontsize{{5.8}}{{7}}\selectfont\itshape] at ({(xa + xb) / 2},{ym + 0.02}) {{{lab}}};")
    o.append(r"\end{tikzpicture}")
    o.append(r"\end{document}")
    (SRC / "fig_overview.tex").write_text("\n".join(o) + "\n")
    print("wrote fig_overview.tex | wire", sorted(wire.quantum_lines), sorted(wire.classical_lines), "| pdg", sorted(pdg.quantum_lines))


if __name__ == "__main__":
    main()
