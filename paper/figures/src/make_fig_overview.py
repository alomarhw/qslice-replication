"""Overview figure: the tool on the motivating Bugs4Q bug (stackoverflow-6-10/bug_2, buggy.py), statically.

Four stages, read left to right: (1) the Qiskit program; (2) srcML of the gate call on line 7, as a tree, with the
quantum fact the tool derives; (3) the operation trace drawn as a circuit with source lines, the criterion and the
kickback dependence; (4) the slice on the source under the wire rule and under the classical PDG. The faulty line
is one colour in every stage and the wire slice another, so the fault can be followed through the pipeline.
Every value is computed from the original file by srcML and the tool (tool/interp.py, tool/slicer.py); the file is
read, never executed. Asserts the slices of Fig. 1 (wire: lines 5-7; classical PDG: line 5) before drawing.
Usage (from the workspace root): python paper/figures/src/make_fig_overview.py BUGS4Q_ROOT
"""

from __future__ import annotations

import re
