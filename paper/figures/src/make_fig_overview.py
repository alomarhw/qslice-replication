def tex(s: str) -> str:
    return (s.replace("\\", r"\textbackslash{}").replace("_", r"\_").replace("{", r"\{").replace("}", r"\}")
            .replace("#", r"\#").replace("%", r"\%").replace("&", r"\&").replace("~", r"\textasciitilde{}"))


def srcml_stmt(path: Path, line: int):
    """srcML element names under the expression statement on `line` (real output of srcML --position)."""
    xml = subprocess.run(["srcml", "--position", "-l", "Python", str(path)], capture_output=True, text=True, check=True).stdout
    m = re.search(r'<expr_stmt pos:start="(%d:\d+)"' % line, xml)
    assert m, "no srcML expr_stmt on that line"
    body = xml[m.start(): xml.index("</expr_stmt>", m.start())]
    names = re.findall(r"<(\w+)[ >]", body)
    for need in ("expr_stmt", "call", "name", "argument_list", "argument", "literal"):
        assert need in names, need
    lits = re.findall(r'<literal type="number"[^>]*>([^<]+)</literal>', body)
    callee = "".join(re.findall(r"<name[^>]*>(\w+)</name>", body.split("<argument_list")[0]))
    return m.group(1), callee, lits


def srcml_fragment(path: Path, line: int) -> str:
    xml = subprocess.run(["srcml", "--position", "-l", "Python", str(path)], capture_output=True, text=True, check=True).stdout
    m = re.search(r'<expr_stmt pos:start="%d:\d+".*?</expr_stmt>' % line, xml, re.S)
    frag = re.sub(r' pos:end="[^"]*"', "", m.group(0))
    head, rest = frag.split(">", 1)
    return head + ">" + re.sub(r' pos:start="[^"]*"', "", rest)



def xml_tex(row: str) -> str:
    """One display row: tags light purple, source text dark and bold, lettered highlights as in the legend."""
    out = []
    for tok in re.findall(r'<[^>]+>|[^<]+', row):
        if tok.startswith("<"):
            t = tex(tok)
            m = re.search(r'pos:start="([^"]+)"', tok)
            if m:
                t = t.replace(tex(m.group(0)), r"\hlbox{" + tex(m.group(0)) + r"}\hlm{d}")
            if tok in ("<call>", "</call>"):
                t = r"\hlbox{" + t + r"}" + (r"\hlm{a}" if tok == "<call>" else "")
            out.append(r"\textcolor{tree}{" + t + "}")
        else:
            body = r"\textcolor{ink}{\bfseries " + tex(tok) + "}"
            if tok in ("cx",):
                body = r"\hlbox{" + body + r"}\hlm{b}"
            if tok in ("0", "1"):
                body = r"\hlbox{" + body + r"}" + (r"\hlm{c}" if tok == "0" else "")
            out.append(body)
    return "".join(out)


def main():
    path = Path(sys.argv[1]) / BUG
    src = path.read_text().splitlines()
    circ = trace_file(path).main_circuit()
    wire = wire_slice(circ, [0])
    pdg = wire_slice(circ, [0], rule="cpdg")
    assert sorted(wire.quantum_lines) == [5, 6, 7] and sorted(wire.classical_lines) == [4], wire
    assert sorted(pdg.quantum_lines) == [5], pdg
    term = terminal(circ)
    ops = [o for k, o in enumerate(circ.ops) if k not in term]
    cx = next(o for o in ops if o.name == "cx")
    pos, callee, lits = srcml_stmt(path, cx.line)
    assert callee.endswith("cx") and lits == ["0", "1"], (callee, lits)

    o = [HEAD]
    dy = 0.36                      # line pitch (cm)
    top = 0.0
    W1, W2, W3, W4, W5, GAP = 2.95, 4.32, 1.95, 2.85, 3.45, 0.42
    X1 = 0.0
    X2 = X1 + W1 + GAP
    X3 = X2 + W2 + GAP
    X4 = X3 + W3 + GAP
    X5 = X4 + W4 + GAP

    def header(x, n, title, w):
        o.append(rf"\node[stnum] (n{n}) at ({x + 0.16},{top + 0.55}) {{{n}}};")
        o.append(rf"\node[stage, anchor=west] at ({x + 0.38},{top + 0.55}) {{{title}}};")
        o.append(rf"\draw[rule, line width=0.6pt] ({x},{top + 0.3}) -- ({x + w},{top + 0.3});")

    # ---------------------------------------------------------------- 1 source
    header(X1, 1, "Qiskit program", W1)
    for i, n in enumerate(SHOW):
        y = top - i * dy
        if n == FAULT:
            o.append(rf"\fill[faultL, rounded corners=1pt] ({X1 + 0.02},{y - 0.15}) rectangle ({X1 + W1 - 0.02},{y + 0.17});")
        o.append(rf"\node[lno] at ({X1 + 0.32},{y}) {{{n}}};")
        o.append(rf"\node[code] at ({X1 + 0.42},{y}) {{{tex(src[n - 1].strip())}}};")
    yf = top - (FAULT - SHOW.start) * dy
    o.append(rf"\node[font=\fontsize{{6.2}}{{7}}\selectfont\bfseries, text=fault, anchor=east] at ({X1 + W1 - 0.06},{yf}) {{fault}};")
    yb = top - len(SHOW) * dy
    o.append(rf"\node[code, text=mute] at ({X1 + 0.42},{yb}) {{\itshape\rmfamily\fontsize{{6.3}}{{8}}\selectfont lines 10--16: simulate, print}};")
    o.append(rf"\node[note, anchor=north west, align=left, text width={W1 - 0.1}cm] at ({X1 + 0.05},{yb - 0.3}) "
             r"{Expected $(\lvert01\rangle{+}\lvert10\rangle)/\sqrt{2}$; line~6 should apply $X$.}")
    o[-1] += ";"

    # ---------------------------------------------------------------- 2 srcML text, with lettered highlights
    header(X2, 2, "srcML of line 7", W2)
    frag = srcml_fragment(path, cx.line)
    # display layout: line breaks and indentation only; joining the rows must give srcML's own text back
    rows = [
        (0, '<expr_stmt pos:start="%s">' % pos),
        (1, "<expr><call>"),
        (2, "<name><name>circuit</name>"),
        (3, "<operator>.</operator><name>cx</name></name>"),
        (2, "<argument_list>(<argument><expr>"),
        (3, '<literal type="number">0</literal>'),
        (3, "</expr></argument>,<argument><expr>"),
        (3, '<literal type="number">1</literal>'),
        (3, "</expr></argument>)</argument_list>"),
        (1, "</call></expr></expr_stmt>"),
    ]
    assert "".join(r for _, r in rows) == frag, ("display rows do not reproduce srcML", frag)
    y0 = top - 0.02
    for i, (d, r) in enumerate(rows):
        o.append(rf"\node[xml] at ({X2 + 0.08 + 0.13 * d},{y0 - i * 0.255}) {{{xml_tex(r)}}};")
    legend = (r"\hl{a}\,\texttt{call} $\to$ one operation\quad \hl{b}\,\texttt{cx} $\to$ gate\\"
              rf"\hl{{c}}\,\texttt{{0}},\,\texttt{{1}} $\to$ $q_{{{lits[0]}}}$ control, $q_{{{lits[1]}}}$ target\\"
              rf"\hl{{d}}\,position $\to$ line {cx.line}\quad \textcolor{{wire}}{{the QDG writes both}}")
    o.append(rf"\node[anchor=north west, align=left, font=\fontsize{{6.2}}{{7.6}}\selectfont, text=ink, inner sep=0pt] at "
             rf"({X2 + 0.08},{y0 - len(rows) * 0.255 - 0.08}) {{{legend}}};")

    # ---------------------------------------------------------------- 3 operation trace (table)
    header(X3, 3, "Trace", W3)
    trow = [r"\textcolor{mute}{line}&\textcolor{mute}{gate}&\textcolor{mute}{qubits}\\[1pt]"]
    for k, op in enumerate(circ.ops):
        qs = r",\,".join("$q_%d$" % next(iter(s_)) for s_ in op.qubits)
        if k in term:
            trow.append(rf"\textcolor{{mute}}{{{op.line}}}&\textcolor{{mute}}{{\texttt{{measure}}}}&\textcolor{{mute}}{{{qs}}}\\[1pt]")
            continue
        bg = "faultL" if op.line == FAULT else "white"
        nm = rf"\texttt{{{op.name}}}"
        trow.append(rf"{op.line}&{nm}&{qs}\\[1pt]")
    o.append(rf"\node[anchor=north west, font=\fontsize{{6.4}}{{8}}\selectfont, text=ink, inner sep=0pt] at ({X3 + 0.06},{top - 0.05}) "
             rf"{{\setlength{{\tabcolsep}}{{3pt}}\begin{{tabular}}{{rll}}{''.join(trow)}\end{{tabular}}}};")
    o.append(rf"\node[note, anchor=north west, align=left, text width={W3 - 0.1}cm] at ({X3 + 0.04},{top - 2.0}) "
             r"{Read statically. Grey measurements are terminal.};")

    # ---------------------------------------------------------------- 4 dependence graph (wire rule)
    header(X4, 4, "QDG", W4)
    gx = X4 + 0.3
    nodes = {}
    for op in ops:
        nodes[op.line] = op
    def gnode(name, x, y, op):
        fill = "wireL" if op.line in wire.quantum_lines else "white"
        drawc = "fault" if op.line == FAULT else "ink"
        qs = ",".join("q%d" % next(iter(s_)) for s_ in op.qubits)
        o.append(rf"\node[gnode, fill={fill}, draw={drawc}{', line width=0.9pt' if op.line == FAULT else ''}] ({name}) at ({x},{y}) {{{op.name} {qs}\\[-1pt]{{\rmfamily\itshape\fontsize{{5.6}}{{6}}\selectfont line {op.line}}}}};")
    h0 = next(op for op in ops if op.name == "h" and next(iter(op.qubits[0])) == 0)
    h1 = next(op for op in ops if op.name == "h" and next(iter(op.qubits[0])) == 1)
    gnode("g0", gx + 0.55, top - 0.35, h0)
    gnode("g1", gx + 1.85, top - 0.35, h1)
    gnode("g2", gx + 1.2, top - 1.4, cx)
    o.append(r"\draw[->, draw=ink!60, line width=0.55pt] (g0) -- node[left, pos=0.45, font=\fontsize{5.6}{6}\selectfont, text=mute] {$q_0$} (g2);")
    o.append(r"\draw[->, draw=ink!60, line width=0.55pt] (g1) -- node[right, pos=0.45, font=\fontsize{5.6}{6}\selectfont, text=mute] {$q_1$} (g2);")
    o.append(rf"\node[rectangle, rounded corners=1.5pt, draw=wire, line width=0.7pt, font=\fontsize{{6.3}}{{7}}\selectfont, text=wire, inner sep=1.8pt] (crit) at ({gx + 1.2},{top - 2.35}) {{criterion $\{{q_0\}}$}};")
    o.append(r"\draw[->, wire, line width=0.9pt] (crit) -- node[right, font=\fontsize{5.6}{6.4}\selectfont, text=wire, align=left] {last writer,\\[-1pt]\texttt{cx} writes $q_0$} (g2);")
    o.append(r"\draw[->, pdg, line width=0.7pt, dash pattern=on 1.6pt off 1.1pt] (crit.west) to[out=180, in=180] (g0.west);")
    o.append(rf"\node[note, anchor=north west, align=left, text width={W4 - 0.1}cm] at ({X4 + 0.04},{top - 2.75}) "
             r"{Shaded nodes are the QDG's backward reach, and the \textcolor{pdg}{dashed} arrow is the classical PDG's last writer.};")

    # ---------------------------------------------------------------- 5 slice on the source
    header(X5, 5, "Slice of $q_0$", W5)
    cw, cp = X5 + 0.2, X5 + 0.68
    o.append(rf"\node[font=\fontsize{{5.8}}{{6.5}}\selectfont\bfseries, text=wire] at ({cw},{top + 0.13}) {{QDG}};")
    o.append(rf"\node[font=\fontsize{{5.8}}{{6.5}}\selectfont\bfseries, text=pdg] at ({cp},{top + 0.13}) {{PDG}};")
    for i, n in enumerate(SHOW):
        y = top - 0.12 - i * dy
        if n == FAULT:
            o.append(rf"\fill[faultL, rounded corners=1pt] ({X5 + 0.02},{y - 0.15}) rectangle ({X5 + W5 - 0.02},{y + 0.17});")
        inw, inp = n in wire.lines, n in pdg.lines
        if inw:
            col = "wire" if n in wire.quantum_lines else "wire!45"
            o.append(rf"\fill[{col}] ({cw - 0.09},{y - 0.1}) rectangle ({cw + 0.09},{y + 0.1});")
        if inp:
            col = "pdg" if n in pdg.quantum_lines else "pdg!50"
            o.append(rf"\fill[{col}] ({cp - 0.09},{y - 0.1}) rectangle ({cp + 0.09},{y + 0.1});")
        o.append(rf"\node[lno] at ({X5 + 1.17},{y}) {{{n}}};")
        o.append(rf"\node[code] at ({X5 + 1.25},{y}) {{{tex(src[n - 1].strip())}}};")
    yf = top - 0.12 - (FAULT - SHOW.start) * dy
    o.append(rf"\node[font=\fontsize{{6.2}}{{7}}\selectfont, text=fault, anchor=north west, align=left] at ({X5 + 0.02},{top - 0.12 - len(SHOW) * dy + 0.05}) "
             r"{\textbf{QDG} keeps the faulty line~6\\\textbf{classical PDG} keeps line~5 only};")
    o.append(rf"\node[note, anchor=north west, align=left, text width={W5 - 0.1}cm] at ({X5 + 0.02},{top - 0.12 - len(SHOW) * dy - 0.55}) "
             r"{A full square marks a quantum line, a light one a classical line that builds the circuit.};")

    # ---------------------------------------------------------------- steps between stages
    for xa, xb in ((X1 + W1, X2), (X2 + W2, X3), (X3 + W3, X4), (X4 + W4, X5)):
        o.append(rf"\draw[flowarrow] ({xa + 0.05},{top + 0.3}) -- ({xb - 0.05},{top + 0.3});")
    o.append(r"\end{tikzpicture}")
    o.append(r"\end{document}")
    (SRC / "fig_overview.tex").write_text("\n".join(o) + "\n")
    print("wrote fig_overview.tex | wire", sorted(wire.quantum_lines), sorted(wire.classical_lines), "| pdg", sorted(pdg.quantum_lines))


if __name__ == "__main__":
    main()
