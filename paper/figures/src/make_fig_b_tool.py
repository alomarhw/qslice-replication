ROLE = {"c": ("gateC", "gateL"), "d": ("qubC", "qubL"), "e": ("bitC", "bitL"), "f": ("condC", "condL")}
_marked = T.marked_tokens


def marked_tokens(shown: str):
    """As srcml_marks.marked_tokens, and a register name whose index is a classical bit is part of that bit."""
    out = _marked(shown)
    for i, (t, m) in enumerate(out):
        if m is None and not t.startswith("<") and out[i + 1:i + 3] and [x for x, _ in out[i + 1:i + 3]] == ["</name>", "<index>"]:
            nxt = next((mm for x, mm in out[i + 3:] if not x.startswith("<") and x.strip("[]() ")), None)
            if nxt == "e":
                out[i] = (t, "e")
    return out


T.marked_tokens = marked_tokens


def render(row_tokens) -> str:
    """A display row of srcML: tags muted, text in ink, the elements the extensions read coloured by role."""
    out = []
    for t, m in row_tokens:
        if t.startswith("<"):
            if m == "g":
                p = re.search(r'pos:start="[^"]*"', t).group(0)
                a, b = T.tex(t).split(T.tex(p))
                out.append(r"\textcolor{tagC}{%s}\role{posC}{posL}{%s}\textcolor{tagC}{%s}" % (a, T.tex(p), b))
            else:
                out.append(r"\textcolor{tagC}{" + T.tex(t) + "}")
        elif m in ROLE:
            out.append(r"\role{%s}{%s}{%s}" % (*ROLE[m], T.tex(t)))
        else:
            out.append(r"\textcolor{ink}{\bfseries " + T.tex(t) + "}")
    return "".join(out)


def fragments():
    xml = subprocess.run(["srcml", "--src-encoding=UTF-8", "--position", "-l", "Python", str(PROG)], capture_output=True, text=True,
                         check=True).stdout
    cx = re.search(r'<expr_stmt pos:start="14:\d+"[^>]*>.*?</expr_stmt>', xml, re.S).group(0)
    cond = re.search(r'<with pos:start="18:\d+"[^>]*>.*?</with>', xml, re.S).group(0)
    out = []
    for frag in (cx, cond):
        head, rest = frag.split(">", 1)
        head = re.sub(r' pos:end="[^"]*"', "", head)
        out.append(head + ">" + T.POS.sub("", rest))
    return out


CH8 = 0.1342  # width of one srcML character (cm), 8pt
T.WRAP = 71


def py_roles(line: str, mark: bool) -> str:
    """A Python line; on the lines srcML is shown for, the same elements carry the same role colours."""
    out = []
    for tok in re.findall(r"\bq\[\w+\]|\bc\[[^\]]*\]|\w+|\s+|.", line):
        t = T.tex(tok).replace(" ", r"\ ")
        if mark and tok.startswith("q["):
            t = r"\role{qubC}{qubL}{%s}" % t
        elif mark and tok.startswith("c["):
            t = r"\role{bitC}{bitL}{%s}" % t
        elif mark and tok == "if_test":
            t = r"\role{condC}{condL}{%s}" % t
        elif mark and tok in T.GATES and out and out[-1].endswith("."):
            t = r"\role{gateC}{gateL}{%s}" % t
        elif tok in ("for", "in", "with"):
            t = r"\textbf{%s}" % t
        out.append(t)
    return "".join(out)


def main():
    circ = trace_file(PROG).main_circuit()
    ops = list(enumerate(circ.ops))
    keep = set(wire_slice(circ, [CRIT]).ops)
    ex = json.load(open(ROOT / "experiments" / "results" / "icpc" / "b_example" / "teleport_chain_q4.json"))
    assert len(ops) == ex["operations"] and len(keep) == ex["slices"][0]["operations"], (len(ops), len(keep))
    src = PROG.read_text().splitlines()

    o = [HEAD]
    WL, WT, WR = 18.0, 9.9, 7.6
    XT, XR = 0.0, 9.9 + 0.5

    def header(x, n, title, w):
        o.append(rf"\node[stnum] at ({x + 0.2},0.5) {{{n}}};")
        o.append(rf"\node[stage] at ({x + 0.45},0.5) {{{title}}};")
        o.append(rf"\draw[rule, line width=0.6pt] ({x},0.28) -- ({x + w},0.28);")

    # ---- 1 the loop's Python (left) and the srcML of lines 14 and 18-19 (right), each line joined to its markup.
    # As in Behler et al.'s figures, srcML tags are dark red and the source text they keep is bold. The key to the
    # role colours sits in the space under the Python.
    o.append(rf"\node[stnum] at (0.2,0.5) {{1}};")
    o.append(r"\node[stage] at (0.45,0.5) {Python source and its srcML, read by E1 and E2};")
    o.append(r"\coordinate (hr) at (0,0.28);")
    PP, XP, NUMX = 0.40, 0.62, 0.12          # Python pitch, code x, line-number x
    XC = 6.45                                 # right edge of the Python card
    XS = 7.55                                 # left edge of the srcML cards
    SP = 0.33                                 # srcML pitch
    ylin = {ln: -0.75 - (ln - 10) * PP for ln in range(10, 22)}
    mapped = {14, 18, 19}
    # Python card
    py_top, py_bot = ylin[10] + 0.33, ylin[21] - 0.2
    o.append(rf"\begin{{scope}}[on background layer]\filldraw[card] (0,{py_top:.3f}) rectangle ({XC},{py_bot:.3f});\end{{scope}}")
    for ln in range(10, 22):
        y = ylin[ln]
        if ln in mapped:
            o.append(rf"\begin{{scope}}[on background layer]\fill[hiband] (0.02,{y - 0.13:.3f}) rectangle ({XC - 0.02},{y + 0.27:.3f});\end{{scope}}")
            num = rf"\role{{posC}}{{posL}}{{{ln}}}"
        else:
            num = str(ln)
        o.append(rf"\node[lab, font=\ttfamily\fontsize{{8}}{{10}}\selectfont] at ({NUMX},{y:.3f}) {{{num}}};")
        o.append(rf"\node[pyline] at ({XP},{y:.3f}) {{{py_roles(src[ln - 1], ln in mapped)}}};")
    # srcML cards, one per statement, all as wide as the widest row
    blocks, ytop = [], py_top
    o.append(r"\begin{scope}[local bounding box=sml]")
    for s_, lines in zip(fragments(), ((14,), (18, 19))):
        top, y = ytop, ytop - 0.27
        for ind, ts, first in T.rows_of(s_):
            x = XS + 0.14 + (CH8 * ind if first else CH8 * (ind + 4))
            lead = "" if first else r"\textcolor{tagC!55}{\rmfamily$\hookrightarrow$}\,"
            o.append(rf"\node[xml] at ({x:.3f},{y:.3f}) {{{lead}{render(ts)}}};")
            y -= SP
        bot = y + SP - 0.17
        blocks.append((top, bot, lines))
        ytop = bot - 0.2
    o.append(r"\end{scope}")
    for k, (top, bot, lines) in enumerate(blocks):
        yt, yb = ylin[lines[0]] + 0.27, ylin[lines[-1]] - 0.13
        o.append(rf"\coordinate (b{k}) at (0,{bot:.3f});")
        o.append(rf"\begin{{scope}}[on background layer]"
                 rf"\fill[link] ({XC},{yt:.3f}) -- ({XS},{top:.3f}) -- ({XS},{bot:.3f}) -- ({XC},{yb:.3f}) -- cycle;"
                 rf"\filldraw[card] ({XS},{top:.3f}) rectangle ([xshift=4pt]sml.east |- b{k});"
                 rf"\end{{scope}}")
    o.append(r"\draw[rule, line width=0.6pt] (hr) -- ([xshift=4pt]sml.east |- hr);")
    o.append(rf"\node[lab, anchor=south west] at (0.05,{py_top + 0.05:.3f}) {{Python, lines 10--21}};")
    o.append(rf"\node[lab, anchor=south west] at ({XS + 0.05},{py_top + 0.05:.3f}) {{srcML of lines 14 and 18--19, with positions}};")
    # the key, under the Python
    chips = [(r"\role{gateC}{gateL}{cx}", "gate, from the role table"),
             (r"\role{qubC}{qubL}{q[src]}", "qubit argument, evaluated in each iteration"),
             (r"\role{bitC}{bitL}{c[2*h+1]}", "classical bit, measured and then tested"),
             (r"\role{condC}{condL}{if\_test}", "condition of the block it opens"),
             (r"\role{posC}{posL}{14}", r"source line, from \texttt{pos:start}")]
    rows = "".join(rf"{{\ttfamily {c}}}&{lab}\\[1pt]" for c, lab in chips)
    ky = py_bot - 0.3
    o.append(rf"\node[lab, anchor=north west, font=\fontsize{{8.5}}{{10}}\selectfont\bfseries, text=ink] at (0.05,{ky:.3f}) "
             rf"{{Read by the extensions}};")
    o.append(rf"\node[anchor=north west, font=\fontsize{{8.5}}{{10}}\selectfont, text=ink, inner sep=0pt] (key) at (0.05,{ky - 0.42:.3f}) "
             rf"{{\setlength{{\tabcolsep}}{{4pt}}\renewcommand{{\arraystretch}}{{1.15}}\begin{{tabular}}{{@{{}}l l@{{}}}}{rows}\end{{tabular}}}};")
    # the quantum markup of line 14, as qiskit2srcml writes it after E1 and E2 (tool/quantum_markup.py): srcML's own
    # elements, with the layer's roles and operations as qu: attributes; inner elements of the arguments elided
    from tool.quantum_markup import markup  # noqa: PLC0415
    qm, _ = markup(PROG)
    QA = "{http://www.srcML.org/srcML/quantum}"
    call = next(c for c in qm.iter(X.S + "call") if X.line(c) == 14)
    args = [a for a in call.iter(X.S + "argument") if a.get(QA + "arg")]
    lt, gt = r"\textless{}", r"\textgreater{}"
    tag = lambda t: rf"\textcolor{{tagC}}{{{lt}{t}}}"  # noqa: E731
    att = lambda k, v, c: rf"\textcolor{{tagC}}{{\ qu:{k}=}}\role{{{c}}}{{{c[:-1]}L}}{{\textquotedbl{{}}{v}\textquotedbl{{}}}}"  # noqa: E731
    row1 = (tag("call") + att("role", call.get(QA + "role"), "gateC") + att("gate", call.get(QA + "gate"), "gateC")
            + att("ops", call.get(QA + "ops"), "posC") + att("qubits", call.get(QA + "qubits"), "posC") + rf"\textcolor{{tagC}}{{{gt}}}")
    txt = lambda a: "".join(a.itertext()).strip().replace("_", r"\_")  # noqa: E731
    arow = lambda a_: (tag("argument") + att("arg", a_.get(QA + "arg"), "qubC") + rf"\textcolor{{tagC}}{{{gt}}}\textbf{{{txt(a_)}}}"  # noqa: E731
                       + rf"\textcolor{{tagC}}{{{lt}/argument{gt}}}")
    rowsq = [row1] + [arow(a_) + ("," if k == 0 else r"\,\textcolor{tagC}{\dots\ {}\textless{}/call\textgreater{}}") for k, a_ in enumerate(args)]
    qtop = blocks[-1][1] - 0.62
    o.append(rf"\node[lab, anchor=south west] at ({XS + 0.05},{qtop + 0.05:.3f}) "
             rf"{{Quantum markup of line 14, written back by \texttt{{qiskit2srcml}}}};")
    for k, r_ in enumerate(rowsq):
        lead = "" if k == 0 else r"\textcolor{tagC!55}{\rmfamily$\hookrightarrow$}\,"
        o.append(rf"\node[xml] at ({XS + 0.14 + (CH8 * 4 if k else 0):.3f},{qtop - 0.27 - k * SP:.3f}) {{{lead}{r_}}};")
    qbot = qtop - 0.27 - (len(rowsq) - 1) * SP - 0.2
    o.append(rf"\begin{{scope}}[on background layer]\filldraw[card] ({XS},{qtop:.3f}) rectangle ([xshift=4pt]sml.east |- 0,{qbot:.3f});\end{{scope}}")
    y = min(qbot, ky - 2.55)
    o.append(rf"\begin{{scope}}[yshift={y - 1.15:.3f}cm]")

    # ---- 2 the trace of line 8 and the first iteration, drawn as a circuit: one column per operation, headed by the
    # source line that appends it, a dot on the control of a CNOT, and the bit a measurement writes or a gate tests.
    header(XT, 2, r"E2: trace of line 8 and iteration $h = 0$, as a circuit", WT)
    first = [op for _, op in ops if (dict(op.iters).get(LOOP) == 0 if op.iters else op.line == 8)]
    qs = sorted({next(iter(qq)) for op in first for qq in op.qubits})
    QX0, DX, WY0, DY = XT + 0.85, 1.0, -0.95, 0.78
    wy = {q: WY0 - r * DY for r, q in enumerate(qs)}
    o.append(rf"\node[lab, anchor=east] at ({QX0 - 0.25},{WY0 + 0.55:.3f}) {{line}};")
    for q in qs:
        o.append(rf"\node[anchor=east, inner sep=0pt, font=\fontsize{{9}}{{11}}\selectfont] at ({QX0 - 0.25},{wy[q]:.3f}) {{\textcolor{{qubC}}{{$q_{{{q}}}$}}}};")
        o.append(rf"\draw[ink!55, line width=0.5pt] ({QX0 - 0.15},{wy[q]:.3f}) -- ({QX0 + DX * (len(first) - 0.4):.3f},{wy[q]:.3f});")
    box = r"draw=gateC, fill=white, line width=0.6pt, minimum width=0.5cm, minimum height=0.42cm, inner sep=1pt, font=\ttfamily\fontsize{8.5}{10}\selectfont, text=gateC"
    for c, op in enumerate(first):
        x = QX0 + 0.35 + c * DX
        o.append(rf"\node[font=\fontsize{{9}}{{11}}\selectfont, text=ink, anchor=base] at ({x:.3f},{WY0 + 0.55:.3f}) {{{op.line}}};")
        qq = [next(iter(a)) for a in op.qubits]
        if op.name == "cx":
            ctl, tgt = qq
            o.append(rf"\draw[gateC, line width=0.7pt] ({x:.3f},{wy[ctl]:.3f}) -- ({x:.3f},{wy[tgt]:.3f});")
            o.append(rf"\fill[gateC] ({x:.3f},{wy[ctl]:.3f}) circle (0.075);")
            o.append(rf"\draw[gateC, line width=0.7pt, fill=white] ({x:.3f},{wy[tgt]:.3f}) circle (0.15);"
                     rf"\draw[gateC, line width=0.7pt] ({x - 0.15:.3f},{wy[tgt]:.3f}) -- ({x + 0.15:.3f},{wy[tgt]:.3f}) ({x:.3f},{wy[tgt] - 0.15:.3f}) -- ({x:.3f},{wy[tgt] + 0.15:.3f});")
        elif op.name == "measure":
            b = next(iter(op.clbits[0]))
            o.append(rf"\node[{box}] at ({x:.3f},{wy[qq[0]]:.3f}) {{M}};")
            o.append(rf"\node[anchor=north, inner sep=0pt, font=\fontsize{{8}}{{9}}\selectfont] at ({x:.3f},{wy[qq[0]] - 0.26:.3f}) {{$\to$\,\textcolor{{bitC}}{{$c_{{{b}}}$}}}};")
        else:
            o.append(rf"\node[{box}] at ({x:.3f},{wy[qq[0]]:.3f}) {{{op.name}}};")
            if op.cond:
                b = next(iter(op.cond))
                o.append(rf"\node[anchor=south, inner sep=0pt, font=\fontsize{{8}}{{9}}\selectfont] at ({x:.3f},{wy[qq[0]] + 0.26:.3f}) {{\textcolor{{condC}}{{if}} \textcolor{{bitC}}{{$c_{{{b}}}$}}}};")
    o.append(rf"\node[lab, anchor=north west, align=left, text width={WT - 0.2}cm] at ({XT + 0.05},{wy[qs[-1]] - 0.55:.3f}) "
             rf"{{Iterations 1 to 3 repeat it on the next qubits. A CNOT, line 14, can change its control "
             rf"\textcolor{{qubC}}{{$q_0$}} as well as its target.}};")

    # ---- 3 slice of q[4] by line and iteration
    header(XR, 3, r"E3: slice of \texttt{q[4]} by line and iteration", WR)
    lines = [12, 13, 14, 15, 16, 17, 19, 21]
    cell, x0, y0 = 0.62, XR + 1.5, -0.95
    o.append(rf"\node[font=\fontsize{{8.5}}{{10}}\selectfont, text=mute, anchor=south east] at ({x0 - 0.08},{y0 + 0.05}) {{line}};")
    for ci, ln in enumerate(lines):
        o.append(rf"\node[font=\fontsize{{9}}{{11}}\selectfont, text=ink, anchor=south] at ({x0 + ci * cell + cell / 2 - 0.02},{y0 + 0.05}) {{{ln}}};")
    for h in range(4):
        yy = y0 - h * cell
        o.append(rf"\node[font=\fontsize{{9}}{{11}}\selectfont, text=mute, anchor=east] at ({x0 - 0.08},{yy - cell / 2}) {{$h = {h}$}};")
        for ci, ln in enumerate(lines):
            k = next(k for k, op in ops if op.line == ln and dict(op.iters).get(LOOP) == h)
            o.append(rf"\draw[draw=wire!60, line width=0.4pt, fill={'wire' if k in keep else 'white'}] "
                     rf"({x0 + ci * cell},{yy}) rectangle ++({cell - 0.05},{-(cell - 0.05)});")
    n_in = len(keep)
    o.append(rf"\node[font=\fontsize{{9}}{{11}}\selectfont, text=ink, anchor=north west, align=left] at ({XR + 0.05},{y0 - 4 * cell - 0.15}) "
             rf"{{line 8 in the slice, line 23 not\enspace\textcolor{{wire}}{{\bfseries {n_in}}} of {len(ops)} operations}};")
    o.append(r"\end{scope}")
    o.append(r"\end{tikzpicture}")
    o.append(r"\end{document}")
    (SRC / "fig_b_tool.tex").write_text("\n".join(o) + "\n")
    print("wrote fig_b_tool.tex | slice", n_in, "of", len(ops))


if __name__ == "__main__":
    main()
