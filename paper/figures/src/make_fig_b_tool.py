"""Paper B: the approach on the teleportation chain of Fig. 1, srcML, the trace it yields, and the slice of q[4].

(1) srcML's own text for line 14, the CNOT whose qubits come from src and a, and lines 18-19, the conditioned repair,
from srcml --position, each under its Python line. The elements the extensions read are coloured by role, as
make_fig_tool.py marks them: the gate name, the qubit arguments, the classical bits and the condition, the with of
if_test, and the position that gives the source line. Tags are muted so that the names stand out.
(2) The trace of the first iteration, one row per operation, with its line.
(3) For every gate line of the loop, its operation in each iteration, filled where it is in the slice of q[4].
Everything comes from srcML and the tool. Asserts that the slice has the size the paper reports
(results/icpc/b_example/teleport_chain_q4.json).
Usage (from the workspace root): python paper/figures/src/make_fig_b_tool.py -> paper/figures/src/fig_b_tool.tex
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent
ROOT = SRC.parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(SRC))
import make_fig_tool as T  # noqa: E402  (shared parsing of srcML into marked rows)
from tool.interp import trace_file  # noqa: E402
from tool.slicer import wire_slice  # noqa: E402

PROG = ROOT / "tool" / "tests" / "big" / "teleport_chain.py"
T.GATES = ("h", "cx", "measure", "x", "z")
T.QUBIT_INDEX_IS_D = True
CRIT = 4
LOOP = 10  # the line of the for loop whose iterations are shown

HEAD = r"""% Generated by make_fig_b_tool.py from teleport_chain.py, srcML and the tool. Do not edit by hand.
\documentclass[tikz,border=2pt]{standalone}
\usepackage[T1]{fontenc}
\usepackage{newtxtext,newtxmath}
\usepackage[varqu,scaled=0.95]{zi4}
\usetikzlibrary{arrows.meta,calc,backgrounds}
\definecolor{ink}{HTML}{1F2328}\definecolor{mute}{HTML}{6E7781}\definecolor{rule}{HTML}{D0D7DE}
\definecolor{tagC}{HTML}{8C959F}\definecolor{srcbg}{HTML}{F3F5F7}\definecolor{wire}{HTML}{24527F}
\definecolor{gateC}{HTML}{24527F}\definecolor{gateL}{HTML}{DCE7F3}
\definecolor{qubC}{HTML}{1A7F64}\definecolor{qubL}{HTML}{D8F0E8}
\definecolor{bitC}{HTML}{A64B00}\definecolor{bitL}{HTML}{FBE7D3}
\definecolor{condC}{HTML}{6639BA}\definecolor{condL}{HTML}{ECE4F8}
\definecolor{posC}{HTML}{1F2328}\definecolor{posL}{HTML}{E1E5E9}
\newcommand{\role}[3]{{\setlength{\fboxsep}{0.6pt}\colorbox{#2}{\strut\textcolor{#1}{\bfseries #3}}}}
\tikzset{
  >={Stealth[length=3.6pt,width=3.2pt]},
  stage/.style={font=\fontsize{9}{11}\selectfont\bfseries, text=ink, anchor=west, inner sep=0pt},
  stnum/.style={circle, draw=ink, line width=0.6pt, font=\fontsize{8}{9}\selectfont\bfseries, text=ink, inner sep=0pt, minimum size=11pt},
  xml/.style={font=\ttfamily\fontsize{8}{10}\selectfont, anchor=west, inner sep=0pt},
  pyline/.style={font=\ttfamily\fontsize{8.5}{10}\selectfont, anchor=west, inner sep=0pt, text=ink},
  lab/.style={font=\fontsize{8.5}{10}\selectfont, anchor=west, inner sep=0pt, text=mute},
  flowarrow/.style={->, line width=0.7pt, draw=ink},
}
\begin{document}
\begin{tikzpicture}
"""

ROLE = {"c": ("gateC", "gateL"), "d": ("qubC", "qubL"), "e": ("bitC", "bitL"), "f": ("condC", "condL")}
_marked = T.marked_tokens


def marked_tokens(shown: str):
    """As make_fig_tool.py, and a register name whose index is a classical bit is part of that bit."""
    out = _marked(shown)
    for i, (t, m) in enumerate(out):
        if m is None and not t.startswith("<") and out[i + 1:i + 3] and [x for x, _ in out[i + 1:i + 3]] == ["</name>", "<index>"]:
            nxt = next((mm for x, mm in out[i + 3:] if not x.startswith("<") and x.strip("[]() ")), None)
            if nxt == "e":
                out[i] = (t, "e")
    return out


T.marked_tokens = marked_tokens


def render(row_tokens) -> str:
    """A display row of srcML: tags muted, text in ink, the elements the extensions read coloured by role."""
    out = []
    for t, m in row_tokens:
        if t.startswith("<"):
            if m == "g":
                p = re.search(r'pos:start="[^"]*"', t).group(0)
                a, b = T.tex(t).split(T.tex(p))
                out.append(r"\textcolor{tagC}{%s}\role{posC}{posL}{%s}\textcolor{tagC}{%s}" % (a, T.tex(p), b))
            else:
                out.append(r"\textcolor{tagC}{" + T.tex(t) + "}")
        elif m in ROLE:
            out.append(r"\role{%s}{%s}{%s}" % (*ROLE[m], T.tex(t)))
        else:
            out.append(r"\textcolor{ink}{\bfseries " + T.tex(t) + "}")
    return "".join(out)


def fragments():
    xml = subprocess.run(["srcml", "--position", "-l", "Python", str(PROG)], capture_output=True, text=True,
                         check=True).stdout
    cx = re.search(r'<expr_stmt pos:start="14:\d+"[^>]*>.*?</expr_stmt>', xml, re.S).group(0)
    cond = re.search(r'<with pos:start="18:\d+"[^>]*>.*?</with>', xml, re.S).group(0)
    out = []
    for frag in (cx, cond):
        head, rest = frag.split(">", 1)
        head = re.sub(r' pos:end="[^"]*"', "", head)
        out.append(head + ">" + T.POS.sub("", rest))
    return out


CH8 = 0.1342  # width of one srcML character (cm), 8pt
T.WRAP = 71


def py_roles(line: str, mark: bool) -> str:
    """A Python line; on the lines srcML is shown for, the same elements carry the same role colours."""
    out = []
    for tok in re.findall(r"\bq\[\w+\]|\bc\[[^\]]*\]|\w+|\s+|.", line):
        t = T.tex(tok).replace(" ", r"\ ")
        if mark and tok.startswith("q["):
            t = r"\role{qubC}{qubL}{%s}" % t
        elif mark and tok.startswith("c["):
            t = r"\role{bitC}{bitL}{%s}" % t
        elif mark and tok == "if_test":
            t = r"\role{condC}{condL}{%s}" % t
        elif mark and tok in T.GATES and out and out[-1].endswith("."):
            t = r"\role{gateC}{gateL}{%s}" % t
        elif tok in ("for", "in", "with"):
            t = r"\textbf{%s}" % t
        out.append(t)
    return "".join(out)


def main():
    circ = trace_file(PROG).main_circuit()
    ops = list(enumerate(circ.ops))
    keep = set(wire_slice(circ, [CRIT]).ops)
    ex = json.load(open(ROOT / "experiments" / "results" / "icpc" / "b_example" / "teleport_chain_q4.json"))
    assert len(ops) == ex["operations"] and len(keep) == ex["slices"][0]["operations"], (len(ops), len(keep))
    src = PROG.read_text().splitlines()

    o = [HEAD]
    WL, WT, WR = 18.0, 7.6, 10.0
    XT, XR = 0.0, 7.6 + 0.4

    def header(x, n, title, w):
        o.append(rf"\node[stnum] at ({x + 0.2},0.5) {{{n}}};")
        o.append(rf"\node[stage] at ({x + 0.45},0.5) {{{title}}};")
        o.append(rf"\draw[rule, line width=0.6pt] ({x},0.28) -- ({x + w},0.28);")

    # ---- 1 the loop's Python (left) and the srcML of lines 14 and 18-19 (right), each line joined to its markup.
    # As in Behler et al.'s figures, srcML tags are muted and the source text they keep is bold.
    header(0, 1, "Python source and its srcML", WL)
    PP, XP, NUMX = 0.40, 0.55, 0.05          # Python pitch, code x, line-number x
    XC = 6.55                                 # right edge of the Python column
    XS = 7.75                                 # left edge of the srcML column
    SP = 0.33                                 # srcML pitch
    ylin = {ln: -0.6 - (ln - 10) * PP for ln in range(10, 22)}
    mapped = {14: 0, 18: 1, 19: 1}
    o.append(rf"\node[lab] at ({NUMX},0.0) {{}};")
    for ln in range(10, 22):
        y = ylin[ln]
        if ln in mapped:
            o.append(rf"\fill[srcbg] ({NUMX - 0.08},{y - 0.12:.3f}) rectangle ({XC},{y + 0.27:.3f});")
            num = rf"\role{{posC}}{{posL}}{{{ln}}}"
        else:
            num = str(ln)
        o.append(rf"\node[lab, font=\ttfamily\fontsize{{8}}{{10}}\selectfont] at ({NUMX},{y:.3f}) {{{num}}};")
        o.append(rf"\node[pyline] at ({XP},{y:.3f}) {{{py_roles(src[ln - 1], ln in mapped)}}};")
    frags = fragments()
    blocks, ytop = [], ylin[14] + 0.45
    for fi, (s_, lines) in enumerate(zip(frags, ((14,), (18, 19)))):
        rows = T.rows_of(s_)
        top = min(ytop, ylin[lines[0]] + 0.45)
        y = top - 0.2
        for ind, ts, first in rows:
            x = XS + 0.1 + (CH8 * ind if first else CH8 * (ind + 4))
            lead = "" if first else r"\textcolor{tagC}{\rmfamily$\hookrightarrow$}\,"
            o.append(rf"\node[xml] at ({x:.3f},{y:.3f}) {{{lead}{render(ts)}}};")
            y -= SP
        bot = y + SP - 0.14
        blocks.append((top, bot, lines))
        ytop = bot - 0.22
    for top, bot, lines in blocks:
        yt, yb = ylin[lines[0]] + 0.27, ylin[lines[-1]] - 0.12
        o.append(rf"\begin{{scope}}[on background layer]"
                 rf"\fill[srcbg] ({XS},{top:.3f}) rectangle ({WL},{bot:.3f});"
                 rf"\fill[srcbg!70!rule] ({XC},{yt:.3f}) -- ({XS},{top:.3f}) -- ({XS},{bot:.3f}) -- ({XC},{yb:.3f}) -- cycle;"
                 rf"\end{{scope}}")
    o.append(rf"\node[lab, anchor=south west] at ({XP},{ylin[10] + 0.32:.3f}) {{Python, lines 10--21}};")
    o.append(rf"\node[lab, anchor=south west] at ({XS + 0.1},{ylin[10] + 0.32:.3f}) {{srcML, with positions}};")
    y = min(blocks[-1][1], ylin[21]) - 0.2
    chips = [(r"\role{gateC}{gateL}{cx}", "gate"),
             (r"\role{qubC}{qubL}{q[src]}", "qubit argument, evaluated in each iteration"),
             (r"\role{bitC}{bitL}{c[2*h+1]}", "classical bit, written by a measurement and read by a condition"),
             (r"\role{condC}{condL}{if\_test}", "conditioned block"),
             (r"\role{posC}{posL}{14}", r"source line, from \texttt{pos:start}")]
    item = [rf"{{\ttfamily {c}}}\ \textcolor{{ink}}{{{lab}}}" for c, lab in chips]
    legend = r"\qquad ".join(item[:3]) + r"\\[2pt]" + r"\qquad ".join(item[3:])
    o.append(rf"\node[anchor=north west, align=left, font=\fontsize{{8.5}}{{10}}\selectfont, inner sep=0pt] at (0.05,{y:.3f}) "
             rf"{{{legend}}};")
    o.append(rf"\begin{{scope}}[yshift={y - 1.75:.3f}cm]")

    # ---- 2 trace of the first iteration
    header(XT, 2, r"Trace of line 8 and iteration $h = 0$", WT)
    rows = [r"\textcolor{mute}{line}&\textcolor{mute}{$h$}&\textcolor{mute}{operation}\\[0pt]"]
    for k, op in ops:
        it = dict(op.iters) if op.iters else {}
        if (it and it.get(LOOP, 0) != 0) or (not it and op.line != 8):
            continue
        qs = r",\,".join(r"\textcolor{qubC}{$q_{%d}$}" % next(iter(op.qubits[j])) for j in range(len(op.qubits)))
        txt = rf"\textcolor{{gateC}}{{\texttt{{{op.name}}}}} {qs}"
        if op.clbits:
            txt += r" $\to$ \textcolor{bitC}{$c_{%d}$}" % next(iter(op.clbits[0]))
        if op.cond:
            txt += r" \textcolor{condC}{if} \textcolor{bitC}{$c_{%d}$}" % next(iter(op.cond))
        h = it.get(LOOP, r"\textcolor{mute}{--}")
        rows.append(rf"{op.line}&{h}&{txt}\\[0pt]")
    rows.append(r"&\textcolor{mute}{1--3}&\textcolor{mute}{the same on the next qubits}\\[0pt]")
    o.append(rf"\node[anchor=north west, font=\fontsize{{9}}{{11}}\selectfont, text=ink, inner sep=0pt] at ({XT + 0.04},-0.05) "
             rf"{{\setlength{{\tabcolsep}}{{5pt}}\begin{{tabular}}{{rll}}{''.join(rows)}\end{{tabular}}}};")

    # ---- 3 slice of q[4] by line and iteration
    header(XR, 3, r"Slice of \texttt{q[4]} by line and iteration", WR)
    lines = [12, 13, 14, 15, 16, 17, 19, 21]
    cell, x0, y0 = 0.62, XR + 1.5, -0.95
    o.append(rf"\node[font=\fontsize{{8.5}}{{10}}\selectfont, text=mute, anchor=south east] at ({x0 - 0.08},{y0 + 0.05}) {{line}};")
    for ci, ln in enumerate(lines):
        o.append(rf"\node[font=\fontsize{{9}}{{11}}\selectfont, text=ink, anchor=south] at ({x0 + ci * cell + cell / 2 - 0.02},{y0 + 0.05}) {{{ln}}};")
    for h in range(4):
        yy = y0 - h * cell
        o.append(rf"\node[font=\fontsize{{9}}{{11}}\selectfont, text=mute, anchor=east] at ({x0 - 0.08},{yy - cell / 2}) {{$h = {h}$}};")
        for ci, ln in enumerate(lines):
            k = next(k for k, op in ops if op.line == ln and dict(op.iters).get(LOOP) == h)
            o.append(rf"\draw[draw=wire!60, line width=0.4pt, fill={'wire' if k in keep else 'white'}] "
                     rf"({x0 + ci * cell},{yy}) rectangle ++({cell - 0.05},{-(cell - 0.05)});")
    n_in = len(keep)
    o.append(rf"\node[font=\fontsize{{9}}{{11}}\selectfont, text=ink, anchor=north west, align=left] at ({XR + 0.05},{y0 - 4 * cell - 0.15}) "
             rf"{{line 8 in the slice, line 23 not\enspace\textcolor{{wire}}{{\bfseries {n_in}}} of {len(ops)} operations}};")
    o.append(rf"\draw[flowarrow] ({XT + WT - 0.3},0.5) -- ({XR - 0.04},0.5);")
    o.append(r"\end{scope}")
    o.append(r"\end{tikzpicture}")
    o.append(r"\end{document}")
    (SRC / "fig_b_tool.tex").write_text("\n".join(o) + "\n")
    print("wrote fig_b_tool.tex | slice", n_in, "of", len(ops))


if __name__ == "__main__":
    main()
