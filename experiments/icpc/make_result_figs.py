from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from tool import TOOL_NAME  # noqa: E402

HERE = Path(__file__).resolve().parents[1]
RES = HERE / "results"
OUT = HERE.parent / "paper" / "figures" / "src"
HEAD = r"""% Generated by experiments/icpc/make_result_figs.py from committed results. Do not edit by hand.
\documentclass[border=2pt]{standalone}
\usepackage[T1]{fontenc}\usepackage{newtxtext,newtxmath}\usepackage[varqu,scaled=0.95]{zi4}
\usepackage{pgfplots}\pgfplotsset{compat=1.18}
\definecolor{cblue}{HTML}{0072B2}\definecolor{cver}{HTML}{D55E00}\definecolor{cora}{HTML}{E69F00}
\definecolor{cgreen}{HTML}{009E73}\definecolor{cgrey}{HTML}{999999}\definecolor{csky}{HTML}{56B4E9}\definecolor{cpurple}{HTML}{7E57C2}
\pgfplotsset{every axis/.append style={font=\footnotesize, tick label style={font=\scriptsize},
  label style={font=\footnotesize}, legend style={font=\scriptsize, draw=none, fill=none},
  axis lines*=left, ymajorgrids, grid style={black!8}}}
\begin{document}
"""


def rows(p):
    return list(csv.DictReader(open(p)))


def robust():
    rob = rows(RES / "icpc" / "rq2_robustness" / "pairs.csv")
    lcq = [r for r in rows(RES / "icpc" / "rq2_robustness_lcq" / "pairs.csv") if r["slicer"] == "lcq" and r["applicable"] == "1"]
    lcqs = [r for r in rows(RES / "icpc" / "rq1_lcq_symbolic" / "robustness.csv") if r["slicer"] == "lcqs"]  # Deviation I-14
    regimes = [("R-basis", "basis inputs"), ("R-haar", "product inputs"), ("R-param", "angle rebinding")]

    def rate(xs):
        return 100 * sum(r["robust"] == "1" for r in xs) / len(xs)
    series = [
        ("QDG", "cblue!75", lambda g: [r for r in rob if r["slicer"] == "lc" and r["regime"] == g]),
        ("commutation", "cgreen!75", lambda g: [r for r in lcq if r["regime"] == g]),
        ("commutation, symbolic angles", "cgreen!35", lambda g: [r for r in lcqs if r["regime"] == g]),
        ("state-based, pruned pairs", "cver!75", lambda g: [r for r in rob if r["slicer"] == "q" and r["regime"] == g and r["pruned"] == "1"]),
    ]
    body = [r"\begin{tikzpicture}\begin{axis}[ybar, bar width=6.5pt, width=8.6cm, height=4.2cm, ymin=0, ymax=140,",
            r" ytick={0,25,50,75,100}, ylabel={pairs still correct (\%)}, symbolic x coords={" + ",".join(l for _, l in regimes) + "},",
            r" xtick=data, enlarge x limits=0.25, nodes near coords, every node near coord/.append style={font=\scriptsize, rotate=90, anchor=west},",
            r" nodes near coords={\pgfmathprintnumber[fixed,precision=0]{\pgfplotspointmeta}},",
            r" legend style={at={(0.5,1.02)}, anchor=south, legend columns=2, /tikz/every even column/.append style={column sep=6pt}}, legend cell align=left, area legend]"]
    for name, col, sel in series:
        body.append(rf"\addplot[fill={col}, draw=none] coordinates {{" + " ".join(f"({l},{rate(sel(g)):.1f})" for g, l in regimes) + "};")
    body.append(r"\legend{" + ",".join("{" + n + "}" for n, _, _ in series) + "}")
    body.append(r"\end{axis}\end{tikzpicture}")
    return HEAD + "\n".join(body) + "\n\\end{document}\n"


def llm():
    t2 = [r for r in rows(RES / "llm" / "t2_scores.csv") if r["split"] == "score" and r["context"] == "context" and r["run"] == "0"]
    hit = defaultdict(list)
    for r in t2:
        hit[(r["arm"], r["input"])].append(int(r["top3"]))
    models = [("claude-sonnet-5-5", "Sonnet 5.5"), ("claude-haiku-5-5", "Haiku 5.5"), ("O-mid", "Qwen-Coder 32B"), ("O-small", "Qwen-Coder 1.5B")]
    inputs = [("full", "full circuit", "cgrey"), ("lc", "QDG slice", "cblue"), ("q", "state-based slice", "cver"), ("du", "def-use slice", "cora")]
    body = [r"\begin{tikzpicture}\begin{axis}[ybar, bar width=5pt, width=8.6cm, height=4.0cm, ymin=0, ymax=100,",
            r" ylabel={fault in top 3 (\%)}, symbolic x coords={" + ",".join(l for _, l in models) + "}, xtick=data, enlarge x limits=0.15,",
            r" xticklabels={" + ",".join("{" + l.replace("Coder ", "Coder\\\\") + "}" for _, l in models) + "}, xticklabel style={align=center},",
            r" legend style={at={(0.5,1.02)}, anchor=south, legend columns=4, /tikz/every even column/.append style={column sep=4pt}}, area legend]"]
    for key, lab, col in inputs:
        body.append(rf"\addplot[fill={col}!80, draw=none] coordinates {{" +
                    " ".join(f"({ml},{100 * st.mean(hit[(m, key)]):.1f})" for m, ml in models) + "};")
    body.append(r"\legend{" + ",".join("{" + l + "}" for _, l, _ in inputs) + "}")
    body.append(r"\end{axis}\end{tikzpicture}")
    return HEAD + "\n".join(body) + "\n\\end{document}\n"


def cost():
    """Per-criterion slicing time and graph build, by measured circuit depth (stages.jsonl keeps every finished
    criterion; at the deepest settings only criteria finished within the 120 s limit exist)."""
    import json
    by = defaultdict(lambda: defaultdict(list))
    for r in map(json.loads, open(RES / "icpc" / "cost" / "stages.jsonl")):
        if r.get("kind") != "F-depth":
            continue
        d = int(r["name"].split("_")[0][1:])
        if r["stage"] == "graph":
            by[d]["build"].append(r["build_seconds"])
            by[d]["depth"].append(r["depth"])
        elif r["stage"].startswith("q:"):
            by[d]["lc"].append(r["lc_seconds"])
            by[d]["q"].append(r["q_seconds"])
    ds = sorted(by)
    xd = {d: st.median(by[d]["depth"]) for d in ds}
    series = [("QDG, per criterion", "cblue", "lc", "*"), ("state-based, per criterion", "cver", "q", "square*"),
              ("QPDG, graph build", "cpurple", "build", "triangle*")]
    ticks = ",".join(str(int(xd[d])) for d in ds)
    body = [r"\begin{tikzpicture}\begin{axis}[width=8.6cm, height=4.4cm, xmode=log, ymode=log, log basis x=2,",
            r" xtick={" + ticks + "}, xticklabels={" + ticks + "}, xlabel={circuit depth (width 8, median of 5 circuits)},",
            r" ylabel={median time}, ymin=3e-5, ymax=600, ytick={1e-4,1e-2,1,100}, yticklabels={0.1\,ms,10\,ms,1\,s,100\,s},",
            r" legend style={at={(0.5,1.02)}, anchor=south, legend columns=2, /tikz/every even column/.append style={column sep=6pt}}, legend cell align=left]"]
    for lab, col, key, mk in series:
        body.append(rf"\addplot[{col}, thick, mark={mk}, mark size=1.5pt] coordinates {{" +
                    " ".join(f"({xd[d]:g},{st.median(by[d][key]):.6f})" for d in ds if by[d][key]) + "};")
    body.append(r"\addplot[black!45, dashed, domain=15:420] {120};")
    body.append(r"\legend{" + ",".join("{" + l + "}" for l, _, _, _ in series) + r",{120 s limit}}")
    body.append(r"\end{axis}\end{tikzpicture}")
    return HEAD + "\n".join(body) + "\n\\end{document}\n"


def size():
    """Mean slice size by width. Corpus L has no dependence floor: its ground truth would need simulation."""
    import json
    N = json.load(open(RES / "icpc" / "numbers.json"))
    bins = ["WTwo", "WFour", "WSeven", "WEleven"]
    coords = ["a", "b", "c", "d", "e"]  # plain coordinates; the labels below hold the dashes and the line break
    ticks = ["2--3", "4--6", "7--10", "11--14", r"{15--20\\corpus L}"]
    series = [("dependence set", "cgrey", "Floor", None), ("QDG", "cblue", "Lc", "CorpusLSizeLc"),
              ("commutation", "cgreen", "Lcq", "CorpusLSizeLcq"), ("QPDG", "cpurple", "Yz", "CorpusLSizeYz")]
    body = [r"\begin{tikzpicture}\begin{axis}[ybar, bar width=5pt, width=8.6cm, height=4.3cm, ymin=0, ymax=100,",
            r" ytick={0,25,50,75,100}, ylabel={slice size (\% of circuit)}, xlabel={circuit width (qubits)},",
            r" symbolic x coords={" + ",".join(coords) + "}, xtick={" + ",".join(coords) + "}, xticklabels={" + ",".join(ticks) + "},",
            r" xticklabel style={align=center}, enlarge x limits=0.13,",
            r" legend style={at={(0.5,1.03)}, anchor=south, legend columns=4, /tikz/every even column/.append style={column sep=4pt}}, area legend]"]
    labels = coords
    for lab, col, key, lkey in series:
        pts = [f"({l},{100 * N[b + key]['value']:.1f})" for b, l in zip(bins, coords)]
        if lkey:
            pts.append(f"({labels[-1]},{100 * N[lkey]['value']:.1f})")
        body.append(rf"\addplot[fill={col}!80, draw=none] coordinates {{" + " ".join(pts) + "};")
    body.append(r"\legend{" + ",".join("{" + l + "}" for l, _, _, _ in series) + "}")
    body.append(r"\end{axis}\end{tikzpicture}")
    return HEAD + "\n".join(body) + "\n\\end{document}\n"


def scale():
    """Time against operations. LintQ's corpus (S1, every stage), QASMBench (S2, every qubit in one pass, reading
    included), our parametric programs (S3, every stage), and on the S2 circuits the baselines, each with Qiskit's
    loading included. Runs that hit the 600 s limit are left out and counted in the text."""
    sc = RES / "icpc" / "scale"
    f = lambda r, ks: sum(float(r[k]) for k in ks if r.get(k))  # noqa: E731
    s1 = [r for r in rows(sc / "s1_lintq.csv") if not r["error"] and r.get("ops")]
    s2 = rows(sc / "s2_qasmbench.csv")
    ops = {r["path"]: int(r["ops"]) for r in s2 if r["tool"] == TOOL_NAME and not r["error"]}
    s3 = rows(sc / "s3_parametric.csv")
    series = [
        (f"{TOOL_NAME}, LintQ corpus", "cgrey!70", "*", [(int(r["ops"]), f(r, ["t_srcml", "t_interp", "t_slice", "t_srcslice", "t_profile"])) for r in s1]),
        (f"{TOOL_NAME}, QASMBench, all qubits", "cblue", "*", [(ops[r["path"]], f(r, ["t_read", "t_terminal", "t_all"])) for r in s2 if r["tool"] == TOOL_NAME and not r["error"]]),
        (f"{TOOL_NAME}, parametric programs", "cgreen", "diamond*", [(int(r["ops"]), f(r, ["t_srcml", "t_interp", "t_all", "t_srcslice"])) for r in s3 if r["tool"] == TOOL_NAME and not r["error"]]),
        ("Qiskit DAG ancestors, one qubit", "cora", "square*", [(ops[r["path"]], f(r, ["t_load", "t_build", "t_one"])) for r in s2 if r["tool"] == "qiskit-dag" and not r["error"] and r["path"] in ops]),
        ("Qiskit LightCone, one qubit", "cver", "triangle*", [(ops[r["path"]], f(r, ["t_load", "t_build", "t_one"])) for r in s2 if r["tool"] == "qiskit-lightcone" and not r["error"] and r["path"] in ops]),
        ("QPDG, build and one slice", "cpurple", "pentagon*", [(ops[r["path"]], f(r, ["t_load", "t_build", "t_one"])) for r in s2 if r["tool"] == "qpdg" and not r["error"] and r["path"] in ops]),
    ]
    body = [r"\begin{tikzpicture}\begin{axis}[width=8.6cm, height=5.2cm, xmode=log, ymode=log, xmin=1, xmax=2e7,",
            r" ymin=1e-3, ymax=2000, xlabel={operations}, ylabel={time}, ytick={1e-3,1e-1,10,1000},",
            r" yticklabels={1\,ms,0.1\,s,10\,s,1000\,s},",
            r" legend style={at={(0.5,1.02)}, anchor=south, legend columns=2, /tikz/every even column/.append style={column sep=6pt}}, legend cell align=left]"]
    for lab, col, mk, pts in series:
        size = "0.6pt" if "LintQ" in lab else "1.6pt"
        body.append(rf"\addplot[only marks, {col}, mark={mk}, mark size={size}] coordinates {{" +
                    " ".join(f"({x},{max(y, 1e-3):.5f})" for x, y in pts if x > 0) + "};")
    body.append(r"\addplot[black!45, dashed, domain=1:2e7] {600};")
    body.append(r"\legend{" + ",".join("{" + l + "}" for l, _, _, _ in series) + r",{600 s limit}}")
    body.append(r"\end{axis}\end{tikzpicture}")
    return HEAD + "\n".join(body) + "\n\\end{document}\n"


def tab_size_robust():
    """The data of fig_size (size by width) and fig_robust (pairs still correct) as one tabular, rule by rule."""
    import json
    N = json.load(open(RES / "icpc" / "numbers.json"))
    bins = ["WTwo", "WFour", "WSeven", "WEleven"]
    rob = rows(RES / "icpc" / "rq2_robustness" / "pairs.csv")
    lcq = [r for r in rows(RES / "icpc" / "rq2_robustness_lcq" / "pairs.csv") if r["slicer"] == "lcq" and r["applicable"] == "1"]
    lcqs = [r for r in rows(RES / "icpc" / "rq1_lcq_symbolic" / "robustness.csv") if r["slicer"] == "lcqs"]
    regimes = ["R-basis", "R-haar", "R-param"]

    def rate(xs):
        return f"{100 * sum(r['robust'] == '1' for r in xs) / len(xs):.1f}"

    def sizes(key, lkey):
        return [f"{100 * N[b + key]['value']:.1f}" for b in bins] + [f"{100 * N[lkey]['value']:.1f}" if lkey else "--"]
    dash = ["--"] * 3
    table = [
        ("Dependence set", sizes("Floor", None), dash),
        (r"\textbf{QDG}", sizes("Lc", "CorpusLSizeLc"), [rate([r for r in rob if r["slicer"] == "lc" and r["regime"] == g]) for g in regimes]),
        ("QPDG", sizes("Yz", "CorpusLSizeYz"), dash),
        ("Commutation", sizes("Lcq", "CorpusLSizeLcq"), [rate([r for r in lcq if r["regime"] == g]) for g in regimes]),
        ("Commutation, symbolic", ["--"] * 5, [rate([r for r in lcqs if r["regime"] == g]) for g in regimes]),
        ("State-based", ["--"] * 5,
         [rate([r for r in rob if r["slicer"] == "q" and r["regime"] == g and r["pruned"] == "1"]) for g in regimes]),
    ]
    out = ["% Generated by experiments/icpc/make_result_figs.py (tab_size_robust) from committed results. Do not edit by hand.",
           r"\begin{tabular}{@{}l *{5}{r} @{\hspace{7pt}} *{3}{r}@{}}", r"\toprule",
           r" & \multicolumn{5}{c}{\textbf{Mean size, \% of circuit}} & \multicolumn{3}{c@{}}{\textbf{Still correct, \%}} \\",
           r"\cmidrule(lr){2-6}\cmidrule(l){7-9}",
           r"\textbf{Rule} & 2--3 & 4--6 & 7--10 & 11--14 & L & Basis & Prod. & Angles \\", r"\midrule"]
    for i, (name, sz, rb) in enumerate(table):
        row = name + " & " + " & ".join(sz + rb) + r" \\"
        if name.startswith(r"\textbf"):
            row = r"\rowcolor{blue!7}" + row
        out.append(row if i == len(table) - 1 else row + r" \arrayrulecolor{black!25}\hline\arrayrulecolor{black}")
    out += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(out) + "\n"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, fn in (("fig_robust", robust), ("fig_llm", llm), ("fig_cost", cost), ("fig_size", size), ("fig_scale", scale)):
        (OUT / f"{name}.tex").write_text(fn())
        print("wrote", OUT / f"{name}.tex")
    (OUT.parent / "tab_size_robust.tex").write_text(tab_size_robust())
    print("wrote", OUT.parent / "tab_size_robust.tex")


if __name__ == "__main__":
    main()
